          pearls at the bottom of the cup — they are the frothy bubbles that
          form on top when the tea is shaken, which is how the earliest cups
          got their name. The pearls themselves are called
          <em>zhēnzhū</em>, "pearls," for their dark, glossy roundness. In
          Taiwan the drink is also known as boba milk tea; the word
          <em>boba</em> originally referred to the large tapioca pearls
          themselves before it came to stand for the whole drink.
        </p>
