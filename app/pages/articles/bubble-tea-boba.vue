          chewy pearls of tapioca that travel up an extra-wide straw. It is
          part drink, part snack, and entirely a product of Taiwan — invented
          there in the 1980s and now sold on high streets from Taipei to
          Toronto, London to Los Angeles.
        </p>
        <p class="section-text">
