        <h2 class="section-title">Overview</h2>
        <p class="section-text">
          <strong>Bubble tea</strong> (珍珠奶茶, <em>zhēnzhū nǎichá</em>,
          literally "pearl milk tea"), known to many outside Asia simply as
          <strong>boba</strong>, is a drink you eat as much as you sip: tea
