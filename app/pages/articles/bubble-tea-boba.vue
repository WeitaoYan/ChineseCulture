          had never tasted one. Long queues outside newly opened shops
          became a familiar sight in cities from Seoul to New York, and
          bubble tea turned from a Taiwanese speciality into a global
          youth-culture staple, mentioned in songs, memes, and everyday
          slang.
        </p>
