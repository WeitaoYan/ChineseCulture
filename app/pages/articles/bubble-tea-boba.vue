        <h2 class="section-title">Two Birthplaces, One Drink</h2>
        <p class="section-text">
          Bubble tea was born in Taiwan in the 1980s, when the island's
          teahouses were looking for new ways to serve tea to a young,
          urban crowd. Until then, tea in Taiwan mostly meant hot tea,
          served slowly in the traditional style. In the early 1980s, some
          teahouses began serving tea cold — shaken with ice and sugar in a
          cocktail shaker, so that it arrived frothy and refreshing. The
          cold, sweet, foamy tea was an instant hit with students and
          office workers, and teahouses began competing to make theirs
          stand out.
        </p>
        <p class="section-text">
          The decisive step — dropping chewy tapioca pearls into the cup —
          is claimed by two rival teahouses, and Taiwan has never quite
          settled the argument. One claim belongs to Chun Shui Tang
          (春水堂) in Taichung, whose staff are said to have added tapioca
          pearls to iced tea in the late 1980s. The other belongs to the
          Hanlin Tea Room (翰林茶館) in Tainan, which says its owner
          created the drink around the same time, using the white tapioca
          pearls traditionally served in desserts. The two shops even
          fought over the invention in court, and the dispute was never
          resolved in either side's favour. Both stories agree on the
          essentials: the drink is Taiwanese, it appeared in the 1980s,
          and the pearls were the stroke of genius that made it different
          from any tea that had come before.
        </p>
        <p class="section-text">
          Tapioca itself was not new to Taiwan. The pearls are made from
          cassava starch — the same starchy root that gives many Asian
          desserts their chew. Taiwanese cooks had long used small
          tapioca pearls in sweet soups and desserts; what the teahouses
          did was put them in a drink, give them a fat straw to travel
          through, and turn a dessert ingredient into the star of the
          show. The pearls are cooked until soft on the outside and
          springy in the middle, then soaked in brown sugar syrup so that
          every pearl carries a little sweetness of its own.
        </p>
