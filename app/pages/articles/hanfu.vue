        <h2 class="section-title">Overview</h2>
        <p class="section-text">
          <strong>Hanfu</strong> (汉服, Hànfú — literally "Han clothing") is
          the traditional dress of the Han Chinese, the majority ethnic group
          of China. With its crossed collar, wide flowing sleeves, sash at
          the waist, and layered robes, hanfu is one of the most recognizable
          silhouettes in the world — and one of the oldest, with a history
          stretching back more than two thousand years.
        </p>
        <p class="section-text">
          Hanfu is not a single costume frozen in time. It is a whole family
          of garments that changed with every dynasty: the bold, bright
          robes of the Tang, the restrained elegance of the Song, the stately
          layered dress of the Ming. What holds them together is a shared
          structure and a shared idea — that clothing should follow the
          natural line of the body, move freely, and carry meaning in every
          colour and motif.
        </p>
        <p class="section-text">
          For centuries hanfu was everyday dress in China, worn by emperors
          and farmers alike. It faded from daily life under the Qing dynasty
          (1644–1912), when Manchu rulers promoted their own style of dress,
          and it all but vanished in the twentieth century. In recent years,
          however, it has come back — worn by young people at festivals, in
          photographs, at graduations, and on city streets, as a living
          expression of cultural pride.
        </p>
