        <h2 class="section-title">The Structure of Hanfu</h2>
        <p class="section-text">
          For all its variety, hanfu is built from a few simple elements.
          A complete outfit is made of separate upper and lower garments,
          layered together and held by sashes rather than buttons or zips —
          a construction that gives hanfu its characteristic flowing line:
        </p>
