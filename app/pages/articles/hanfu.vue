        <h2 class="section-title">Tang, Song, and Ming Styles</h2>
        <p class="section-text">
          Ask a hanfu enthusiast which dynasty's style they love best and
          you will start a friendly argument. Each of the great eras gave
          hanfu a different character:
        </p>
        <FeatureGrid>
          <FeatureItem title="Tang Dynasty (618–907) — Bold &amp; Bright" theme="red">
            <p>
              Tang hanfu is the most exuberant of all. Women's dress
              featured a short jacket worn with a skirt tied high above
              the waist, almost under the arms, in vivid reds, greens, and
              golds. Wide sleeves, flowing trains, and elaborate hair
              ornaments completed the look. Tang art — the murals of the
              Mogao Caves and the court paintings of the period — shows
              women in these bright, confident robes, and the style
              remains the most popular choice for hanfu photography today.
            </p>
          </FeatureItem>
          <FeatureItem title="Song Dynasty (960–1279) — Quiet &amp; Refined" theme="blue">
            <p>
              Song hanfu turned inward. Colours grew softer — pale blues,
              whites, and light greens — and the silhouette grew slimmer
              and more restrained. The <em>beizi</em> (褙子), a long,
              straight outer jacket with side slits, became the signature
              Song garment for both men and women. Song style suits the
              dynasty's art and philosophy: quiet, scholarly, and
              understated, with beauty in proportion rather than display.
            </p>
          </FeatureItem>
          <FeatureItem title="Ming Dynasty (1368–1644) — Stately &amp; Layered" theme="gold">
            <p>
              Ming hanfu is the most formal and complete. The Ming court
              restored Han dress in full, and its garments are layered,
              structured, and richly embroidered. Men's formal robes
              (<em>ao</em>, 袄) and the <em>mamianqun</em> (马面裙), the
              pleated "horse-face skirt" worn by women, are Ming classics
              that survive as the standard image of hanfu in many people's
              minds. Ming styles are a favourite for weddings and formal
              occasions in the modern revival.
            </p>
          </FeatureItem>
