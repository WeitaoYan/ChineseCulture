      <section class="section">
        <h2 class="section-title">The Modern Hanfu Revival</h2>
        <p class="section-text">
          For most of the twentieth century, hanfu existed mainly in
          museums, opera costumes, and historical dramas. The modern
          revival is often traced to 2003, when a young man in Zhengzhou
          wore a hanfu robe in public and shared photographs of it online.
          The images spread, and a movement began: first a handful of
          enthusiasts, then clubs at universities, then shops, festivals,
          and a whole community of makers, photographers, and wearers.
        </p>
        <p class="section-text">
          Today hanfu is worn by young people across China and beyond.
          They wear it to traditional festivals such as the Mid-Autumn
          Festival and the Qixi Festival, to graduations and weddings, to
          historical sites and gardens, and simply for a walk in the park
          with friends. Social media has carried it further: hanfu
          photography, styling guides, and short videos introduce the
          robes to audiences around the world, and hanfu gatherings now
          take place in cities far from China.
        </p>
        <p class="section-text">
          The revival is not about dressing up in a museum piece. Makers
          study old paintings, tomb finds, and museum collections to
          reconstruct historical styles faithfully, while wearers mix
          traditional robes with modern life — a hanfu jacket with jeans,
          a Ming-style skirt at a graduation ceremony. The point, for
          most wearers, is simple: a beautiful garment, made in a Chinese
          way, worn with pride. Two thousand years after the Han dynasty
          gave it its name, hanfu is being worn again — not as a relic,
          but as a living part of Chinese culture.
        </p>
