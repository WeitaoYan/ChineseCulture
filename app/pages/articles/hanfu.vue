        <p class="section-text">
          In hanfu, nothing is merely decorative. Colours and motifs are a
          language, and a robe could say a great deal about the person
          wearing it:
        </p>
        <FeatureGrid>
          <FeatureItem title="🐉 Dragons &amp; Phoenixes" theme="gold">
            <p>
              The dragon (龙) stands for imperial power, strength, and good
              fortune; the phoenix (凤凰) stands for grace, virtue, and the
              empress. Worn together, dragon and phoenix signify harmony
              between husband and wife, and they remain the classic motif
              for wedding hanfu.
            </p>
          </FeatureItem>
          <FeatureItem title="🕊️ Cranes &amp; Peonies" theme="red">
            <p>
              The crane (鹤) is a symbol of longevity and the Daoist
              immortal, often shown flying among clouds. The peony (牡丹),
              known as the "king of flowers", stands for wealth, honour,
              and beauty. Both appear constantly in hanfu embroidery, and
              both are wishes as much as decorations: long life, good
              fortune, a flourishing family.
            </p>
          </FeatureItem>
          <FeatureItem title="🎨 Colour" theme="blue">
            <p>
              Colour carried rank and meaning. Yellow was long associated
              with the emperor and the centre of the world; red meant joy
              and celebration, and is still the colour of wedding dress;
              white was the colour of mourning. The five traditional
              colours — blue-green, red, yellow, white, and black — echo
              the Five Elements (五行) and the order of the cosmos itself.
            </p>
          </FeatureItem>
          <FeatureItem title="☁️ Clouds &amp; Waves" theme="gray">
            <p>
              Flowing cloud patterns (祥云) and wave borders are among the
              oldest motifs in Chinese dress. They suggest the movement of
              heaven and water, and they suit the flowing lines of the
              robe itself. A cloud collar, a wave-patterned hem, a sash
              knotted like a cloud — the garment is meant to move like
              weather.
            </p>
