              clear "Y" shape at the chest. The opposite crossing, left
              over right, was traditionally reserved for the dress of the
              dead, so the direction of the cross was a matter of custom
              and respect, not chance.
            </p>
          </FeatureItem>
          <FeatureItem title="Wide Sleeves (宽袖)" theme="red">
            <p>
              Hanfu sleeves are wide and open, falling well past the wrist
              and sometimes to the knee. In formal dress they could be very
              broad indeed — a sign of dignity and leisure, since wide
              sleeves are no help at all with manual work. The sleeve is
              also practical in its own way: a wide sleeve could hold a
              fan, a letter, or a small treasure.
            </p>
          </FeatureItem>
          <FeatureItem title="The Sash (腰带)" theme="blue">
            <p>
              Instead of buttons, hanfu is fastened with ties and sashes.
              A cloth sash or a belt at the waist holds the robe in place
              and shapes its silhouette; a jade pendant or a sachet might
              hang from it. The sash is both functional and decorative,
              and its knot is part of the art of wearing hanfu well.
            </p>
          </FeatureItem>
          <FeatureItem title="Layers &amp; Skirts (衣裳)" theme="green">
