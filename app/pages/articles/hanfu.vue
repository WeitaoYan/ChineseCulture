      <section class="section">
        <h2 class="section-title">A History in Robes</h2>
        <p class="section-text">
          The roots of hanfu reach back to the earliest Chinese dynasties.
          Tradition credits the Yellow Emperor with the first crown and
          robes, and by the Zhou dynasty (c. 1046–256 BCE) the crossed-collar
          robe was already the standard dress of the educated classes. But
          hanfu takes its name from the Han dynasty (206 BCE–220 CE), when
          the robe system was formalized: officials wore robes whose colour,
          fabric, and ornament marked their rank, and the style spread
          across a newly unified empire.
        </p>
        <p class="section-text">
          In the centuries that followed, each dynasty made the robe its
          own. During the Wei and Jin period (3rd–5th centuries), scholars
          and artists favoured loose, flowing robes that suited an age of
          philosophy and free talk. The Tang dynasty (618–907), confident
          and cosmopolitan, made hanfu bolder than ever: bright colours,
          high-waisted skirts for women, and influences arriving along the
          Silk Road. The Song dynasty (960–1279) turned toward restraint and
          refinement, while the Ming dynasty (1368–1644) — founded by Han
          Chinese after Mongol rule — deliberately restored Han dress and
          gave it its most formal, layered expression.
        </p>
        <p class="section-text">
          The great break came with the Qing dynasty. After the Manchu
          conquest in 1644, the Qing court ordered Han men to adopt Manchu
          dress and hairstyle — the famous queue order of 1645, which
          required men to shave the front of the head and wear a braid, and
          to wear Manchu-style robes in official life. Women's dress was
          less strictly controlled, and Han styles survived longer among
          women, but over the following centuries the flowing robes of the
          Han gradually gave way to the narrower, fitted garments of the
          Manchu tradition. By the early twentieth century, hanfu had
          largely disappeared from everyday life, surviving mainly in
          opera costume, ritual dress, and paintings.
        </p>
      </section>

