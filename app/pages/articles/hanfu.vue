              often a long skirt for women or loose trousers for men. The
              classic women's ensemble pairs a short jacket (<em>ru</em>,
              襦) with a long, high-waisted skirt (<em>qun</em>, 裙),
              while men wore long robes (<em>pao</em>, 袍) over trousers.
              Layers could be added or removed with the season, and the
              glimpse of one colour beneath another was part of the beauty.
            </p>
          </FeatureItem>
        </FeatureGrid>
        <p class="section-text">
          Two things hanfu does not have are as telling as what it does.
          There are no buttons down the front and no tight tailoring to the
          body. The garment hangs from the shoulders and moves with the
          wearer, which is why hanfu looks so graceful in motion — and why
          it suits dance, opera, and ceremony so well.
        </p>
