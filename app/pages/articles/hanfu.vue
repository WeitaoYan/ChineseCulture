      <section class="section">
        <h2 class="section-title">Hanfu and Qipao: Not the Same</h2>
        <p class="section-text">
          Visitors to China often confuse hanfu with the qipao (旗袍,
          also called the cheongsam) — and the confusion is understandable,
          since both are famous Chinese garments. But they come from
          different peoples and different centuries, and they look
          completely different once you know what to look for.
        </p>
        <p class="section-text">
          The qipao descends from the robes of the Manchu bannermen — the
          <em>qi</em> (旗) in its name means "banner". Its modern form,
          the fitted dress with a high standing collar, side slits, and
          frog buttons, took shape in Shanghai in the 1920s and 1930s.
          It is close-fitting and tailored to the body, and it belongs to
          the twentieth century.
        </p>
        <p class="section-text">
          Hanfu is far older and far looser: a Han Chinese garment with a
          crossed collar, wide sleeves, a sash, and layered robes that
          hang from the shoulders rather than fitting the body. Where the
          qipao shows the figure, hanfu hides it in flowing cloth. Both
          are genuinely Chinese — but they tell two different stories, and
          part of appreciating either one is knowing which is which.
        </p>
      </section>

