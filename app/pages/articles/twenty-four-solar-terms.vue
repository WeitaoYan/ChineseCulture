        <p class="section-text">
          On 30 November 2016, UNESCO inscribed the Twenty-Four Solar Terms
          on the Representative List of the Intangible Cultural Heritage of
          Humanity. The listing recognised the terms not as a relic, but as a
          living system: still used by farming communities, still taught to
          schoolchildren, and still celebrated in festivals and seasonal food
          across China.
        </p>
        <p class="section-text">
          The terms have also travelled. Versions of the system are used in
          Korea, Japan, and Vietnam, each adapted to local climates and crops,
          and Chinese communities around the world still mark Qingming, the
          Winter Solstice, and Beginning of Spring far from the Yellow River
          valley where the system began. Modern China has given the terms new
          life as well: they appear in textbooks, weather reports, and even in
          the opening ceremony of the Beijing 2022 Winter Olympics, where each
          term was counted down in turn.
        </p>
        <p class="section-text">
          The legacy of the solar terms is a way of paying attention. They ask
          you to notice the first rain, the first frost, the day the light
          begins to return — and to live by what you notice. In a world of
          fixed calendars and indoor work, that is a quieter, older kind of
          wisdom, and it is still being practised, term by term, year by year.
        </p>
