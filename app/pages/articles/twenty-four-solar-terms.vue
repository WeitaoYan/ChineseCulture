        <h2 class="section-title">Farming, Festivals, and Daily Life</h2>
        <p class="section-text">
          The solar terms were never just astronomy. They were the working
          calendar of a farming civilisation, and their advice is still
          practical: sow at Grain Rain, harvest at Grain in Ear, store at
          Frost's Descent, rest at Major Snow. Chinese farmers still quote the
          old sayings tied to each term, and agricultural programmes still
          publish sowing dates by solar term rather than by month alone.
        </p>
        <p class="section-text">
          The terms also shape the table. Each season has its foods: spring
          pancakes at Beginning of Spring, cold noodles at the Summer Solstice,
          crabs at Cold Dew, dumplings at the Winter Solstice, laba congee near
          Minor Cold. Traditional Chinese medicine reads the terms the same
          way, advising lighter food and more rest in the heat, warming food
          and early nights in the cold — health advice that follows the sun,
          term by term.
        </p>
        <p class="section-text">
          For visitors to China, the terms are a useful key to the year. If a
          festival falls near Qingming, expect tomb-sweeping and kite-flying;
          near the Winter Solstice, expect family dinners; near Beginning of
          Spring, expect the first signs of the new year. The terms explain
          why Chinese festivals fall when they do — not on fixed dates, but on
          the sun's turning points, year after year.
        </p>
