        <h2 class="section-title">Overview</h2>
        <p class="section-text">
          <strong>The Twenty-Four Solar Terms</strong> (二十四节气,
          Èrshísì Jiéqì) are China's ancient way of dividing the year — not
          by months alone, but by the sun's journey across the sky. Each term
          marks a small, precise change in the seasons: the first thaw, the
          first rain, the first frost, the longest day, the coldest night. For
          more than two thousand years, farmers have used them to decide when
          to sow, when to harvest, and when to rest — and families still use
          them today to mark festivals, food, and the turning of the year.
        </p>
        <p class="section-text">
          The system grew out of the farming life of the Yellow River valley,
          where the changing seasons decided whether a family ate well or went
          hungry. Early forms of the terms appear in texts from around the
          Western Han dynasty, and the full set of twenty-four was formalised
          in the Taichu calendar of 104 BCE. From there the terms spread across
          China and into Korea, Japan, and Vietnam, becoming one of East Asia's
          shared ways of reading the year.
        </p>
        <p class="section-text">
          In 2016, UNESCO inscribed the Twenty-Four Solar Terms on the
          Representative List of the Intangible Cultural Heritage of Humanity,
          recognising them as a living tradition — still used by farmers,
          still taught in schools, and still woven into festivals such as
          Qingming and the Winter Solstice. They are, in a sense, China's
          oldest weather forecast: a calendar written not in numbers, but in
          rain, blossom, heat, and snow.
        </p>
      </section>

