        </p>
        <FeatureGrid>
          <FeatureItem title="立夏 Lìxià — Beginning of Summer (around May 5–7)" theme="green">
            <p>
              Summer begins. Crops enter their fastest growth, and people
              traditionally weigh themselves — hoping to grow as sturdily as
              the crops — and eat eggs, said to keep the heart strong in the
              heat.
            </p>
          </FeatureItem>
          <FeatureItem title="小满 Xiǎomǎn — Grain Buds (around May 20–22)" theme="yellow">
            <p>
