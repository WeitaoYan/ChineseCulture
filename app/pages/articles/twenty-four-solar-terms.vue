        <h2 class="section-title">How the System Works</h2>
        <p class="section-text">
          The Chinese calendar is lunisolar: its months follow the moon, but
          its year is kept in step with the sun. The solar terms are the solar
          half of that bargain. The sun's apparent path through the sky — the
          ecliptic — is divided into 24 equal parts of 15 degrees each. Every
          time the sun enters a new 15-degree segment, a new term begins.
          Because the sun moves steadily, the terms fall on nearly the same
          dates every year, shifting by only a day or two.
        </p>
        <p class="section-text">
          The twenty-four terms are grouped into four seasons of six terms
          each. Each season opens with a "Beginning" (立, lì) — Beginning of
          Spring, Beginning of Summer, Beginning of Autumn, Beginning of
          Winter — and closes near a solstice or equinox. In between, the
          terms track the weather a farmer actually feels: rain arriving,
          insects waking, grain filling, dew turning white, snow falling, cold
          deepening. The names are plain and practical, because they were made
          to be used, not admired.
        </p>
        <p class="section-text">
          The terms also anchor the festival year. Qingming is both a solar
          term and a festival for honouring ancestors. The Winter Solstice is
          both a term and a family feast day. Beginning of Spring opens the
          farming year and, in folk custom, the new year's luck. To know the
          terms is to know when China eats dumplings, sweeps tombs, flies
          kites, and waits for the first spring rain.
        </p>
      </section>

