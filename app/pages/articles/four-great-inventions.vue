          made writing cheap. Printing made books plentiful. The compass made
          the oceans crossable. Gunpowder made old walls and old armies
          obsolete. Together they helped end the age when knowledge, trade,
          and power belonged only to the few who lived near a coast, a court,
          or a monastery.
        </p>
