        <h2 class="section-title">Paper: Writing for Everyone</h2>
        <p class="section-text">
          Before paper, Chinese writing was carved onto bamboo slips or brushed
          onto silk. Bamboo was heavy — a single long text could fill a cart —
          and silk was far too expensive for everyday use. Archaeologists have
          found fragments of early paper in China dating back to the Western
          Han dynasty, in the 2nd century BCE, but paper only became reliable
          and widely used after the court official Cai Lun (蔡伦) improved the
          process and presented it to Emperor He of Han in 105 CE.
        </p>
        <p class="section-text">
          Cai Lun's method used bark, hemp, rags, and old fishing nets, soaked,
          beaten into pulp, and spread thin to dry into sheets. The ingredients
          were cheap and plentiful, and the result was light, smooth, and easy
          to fold, carry, and store. Within a few centuries paper had replaced
          bamboo and silk across China, and it transformed government, literature,
          and education: officials could keep detailed records, scholars could
          copy the classics, and ordinary people could write letters.
        </p>
        <p class="section-text">
          Papermaking spread slowly westward — to Korea and Japan, then to
          Central Asia, and eventually, by around the 12th century, to Europe.
          Wherever it arrived, the same change followed: writing stopped being
          a luxury material and became a daily tool. Without cheap paper,
          printing would have had nothing to print on, and the spread of
          knowledge that followed would have been far slower.
        </p>
