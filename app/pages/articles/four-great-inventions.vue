          alchemists, trying to brew an elixir of life, mixed saltpetre,
          sulphur, and charcoal — and discovered that the mixture burned with
          a sudden, violent flash. The earliest known written formula for
          gunpowder dates to around the 9th century, and early writers warned
          that the mixture could burn down houses if handled carelessly.
        </p>
        <p class="section-text">
          The Chinese first put gunpowder to peaceful and festive uses: fireworks
          to frighten away evil spirits at festivals, and firecrackers whose
          noise was believed to drive off the legendary beast Nian at the
          Spring Festival. But by the Song dynasty it had also become a weapon.
          Song armies used fire arrows, explosive bombs thrown from catapults,
          and early hand-held guns. By the 13th century, gunpowder weapons were
          spreading westward along the trade routes, carried in part by the
          Mongol conquests, and reached Europe in the same century.
        </p>
        <p class="section-text">
          Gunpowder's legacy is the most double-edged of the four. It gave the
          world fireworks and celebration, new tools for mining and building —
          and weapons that changed warfare forever. It is the one invention of
          the four whose inventors, seeking long life, instead created something
          that could take life away. That tension is part of why the story is
          still told: invention is never only about the idea, but about what
          people choose to do with it.
        </p>
