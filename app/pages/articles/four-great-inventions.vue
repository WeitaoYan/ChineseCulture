          is the ancestor of every book, newspaper, and printer on a desk. The
          compass lives on in the magnetometer inside a smartphone, pointing
          the map that guides a walk across a city. Gunpowder lives on in
          fireworks that light up festivals from the Spring Festival to New
          Year's Eve around the world. The inventions are no longer Chinese or
          European or Arab — they belong to everyone, which is exactly what
          makes their origin worth remembering.
        </p>
