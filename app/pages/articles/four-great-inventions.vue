        <p class="section-text">
          The compass began not as a sailor's tool but as a fortune-teller's.
          In the Han dynasty, diviners used a lodestone spoon — a piece of
          naturally magnetic rock carved into the shape of a spoon — that
          turned on a smooth bronze plate to point south. The device was called
          the <em>sinan</em> (司南), "the south-pointer," and it was used in
          geomancy and ritual, not navigation.
        </p>
        <p class="section-text">
          By the Song dynasty, Chinese sailors had learned a more practical
          trick: magnetise an iron needle and float it in water, or balance it
          on a pivot, and it will settle pointing north and south. Shen Kuo's
          <em>Dream Pool Essays</em>, written around 1088, describes the
          magnetic needle compass and notes that it points slightly off true
          south — an early observation of magnetic declination. Song ships used
          the compass on long voyages across the South China Sea and the Indian
          Ocean, carrying ceramics, silk, and tea to ports as far away as the
          Middle East and East Africa.
        </p>
        <p class="section-text">
          The compass reached Europe by around the 12th to 13th century, most
          likely through Arab traders. It changed seafaring everywhere it went:
          sailors no longer had to hug the coast or wait for clear skies to
          steer by the stars. Open-ocean voyages — and with them, the age of
          exploration and global trade — became possible.
        </p>
