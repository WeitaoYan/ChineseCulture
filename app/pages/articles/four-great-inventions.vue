        <h2 class="section-title">Printing: Books for the Many</h2>
        <p class="section-text">
          Hand-copying a book is slow work, and every copy risks new mistakes.
          In the Tang dynasty, Chinese craftsmen found a faster way: carve a
          whole page of text in reverse on a wooden block, ink it, and press
          paper onto it. The oldest surviving dated printed book in the world,
          the <em>Diamond Sutra</em>, was printed this way in China in 868 CE.
          Woodblock printing soon produced Buddhist texts, calendars, and
          almanacs in large numbers.
        </p>
        <p class="section-text">
          The next step came in the Northern Song dynasty. Around the 1040s, a
          craftsman named Bi Sheng (毕昇) invented movable type: he moulded
          individual characters from clay, fired them hard, and set them in an
          iron frame with resin and wax. When a page was printed, the type
          could be taken apart and reused for the next page. The idea was
          recorded by the scholar Shen Kuo in his <em>Dream Pool Essays</em>
          (梦溪笔谈), written in the late 11th century — one of the reasons we
          know Bi Sheng's name at all.
        </p>
        <p class="section-text">
          Movable type was harder to use in China than in Europe, because
          Chinese writing needs thousands of characters rather than a few dozen
          letters. Wooden and later metal movable type was still used, and
          woodblock printing remained common for centuries. But the principle
          was the same one that would later transform Europe: once a text could
          be set in type and printed again and again, knowledge no longer
          depended on a scribe's hand — or on a single copy surviving.
        </p>
