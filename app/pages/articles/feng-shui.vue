      <section class="section">
        <h2 class="section-title">Feng Shui at Home</h2>
        <p class="section-text">
          Most people meet feng shui not in a mountain valley but in their
          own living room. The classic advice for a home follows a few
          simple principles — and many of them make plain practical sense,
          whatever one believes about qi:
        </p>
        <FeatureGrid>
          <FeatureItem title="🚪 The Front Door" theme="red">
            <p>
              The door is called the "mouth of qi," where energy enters the
              home. It should open freely, be well lit, and lead into a
              clear space — not face a wall, a staircase, or a pile of
              shoes. A welcoming entrance is said to invite good fortune
              in, and it certainly makes a better first impression.
            </p>
          </FeatureItem>
          <FeatureItem title="🛏️ The Bed" theme="blue">
            <p>
              The bed should stand against a solid wall — the "mountain" at
              your back — with a clear view of the door, but not directly in
              line with it. This "commanding position" is said to bring
              restful sleep and a sense of security, and it matches how
              most people instinctively arrange a bedroom.
            </p>
          </FeatureItem>
          <FeatureItem title="🖥️ The Desk" theme="gold">
            <p>
              Like the bed, a desk works best with a solid wall behind it
              and the door in view. Sitting with your back to the door is
              said to leave you exposed and distracted; facing the room is
              believed to support focus, authority, and career luck.
            </p>
          </FeatureItem>
          <FeatureItem title="🍳 The Kitchen and Stove" theme="green">
            <p>
              The stove represents wealth and nourishment, since it is
              where food — and therefore the family's health — is made. It
              should not sit directly opposite a sink or a tap, because in
              the five-element cycle water extinguishes fire. Keep it clean
              and working: a broken stove is considered bad feng shui.
            </p>
          </FeatureItem>
          <FeatureItem title="🪞 Mirrors" theme="gray">
            <p>
              Mirrors are powerful tools in feng shui because they reflect
              and redirect qi. A mirror that doubles a beautiful view or a
              dining table is considered lucky; one facing the bed or the
              front door is traditionally avoided, since it is said to
              bounce energy — and rest — straight back out.
            </p>
          </FeatureItem>
          <FeatureItem title="🧹 Clutter" theme="yellow">
            <p>
              The one rule almost every feng shui master agrees on is also
              the simplest: clear the clutter. Blocked hallways, jammed
              cupboards, and broken objects are said to stagnate qi. Whether
              or not energy is involved, a tidy, unblocked home is easier to
              live in — and that is a result anyone can feel.
            </p>
          </FeatureItem>
        </FeatureGrid>
      </section>

