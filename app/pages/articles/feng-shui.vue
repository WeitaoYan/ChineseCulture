      <section class="section">
        <h2 class="section-title">A Long History</h2>
        <p class="section-text">
          Feng shui grew out of the oldest Chinese concerns: where to
          settle and where to bury the dead. Long before it had a name,
          people in China were already choosing burial sites on sunny,
          sheltered hillsides near water, believing the resting place of
          ancestors would affect the fortune of their descendants. This
          practice, called <em>kan yu</em> (堪舆, "observing heaven and
          earth"), is the root from which feng shui grew.
        </p>
        <p class="section-text">
          The earliest surviving text on the subject is the
          <em>Book of Burial</em> (葬书, Zàngshū), traditionally attributed
          to the scholar Guo Pu (郭璞, c. 276–324) of the Jin dynasty,
          though scholars believe the text as we have it may have been
          compiled later. It is in this book that the term
          <em>feng shui</em> first appears, and it sets out the core idea:
          qi rides on the wind and scatters, but is held back when it meets
          water — so a good site must hide from the wind and gather water.
        </p>
        <p class="section-text">
          Over the following centuries, feng shui developed into two great
          approaches. The <em>Form School</em> (峦头派), associated with
          southern China, reads the landscape itself: the shapes of
          mountains, the bends of rivers, the rise and fall of the ground.
          The <em>Compass School</em> (理气派), associated with the north,
          works with directions, the magnetic compass, and the cycles of
          time. By the Song dynasty (960–1279), the compass had become the
          feng shui master's essential tool, and masters of both schools
          advised emperors, officials, and families on matters as large as
          a capital city and as small as a kitchen stove. The system was
          carried to Korea, Japan, and Vietnam, and later, with Chinese
          emigrants, around the world.
        </p>
      </section>

