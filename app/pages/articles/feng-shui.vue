      <section class="section">
        <h2 class="section-title">Cities and Buildings Shaped by Feng Shui</h2>
        <p class="section-text">
          Feng shui was never only about houses. Chinese capitals were
          chosen and laid out with its principles in mind, and the greatest
          example stands in the heart of Beijing: the Forbidden City. Built
          in the early 15th century under the Yongle Emperor, the palace
          complex sits on a strict north–south axis, with mountains to the
          north and water to the south — the ideal feng shui setting. Its
          main halls face south to catch the sun, its gates open along the
          central axis, and the whole city of Beijing grew outward from
          that line. To walk its axis today is to walk through a feng shui
          diagram built in stone and timber. See our article on
          <NuxtLink to="/articles/forbidden-city">The Forbidden City</NuxtLink>.
        </p>
        <p class="section-text">
          In modern times, feng shui has shaped skylines too. In Hong Kong,
          where the tradition remains strong, major buildings are routinely
          designed with feng shui advice — from the placement of entrances
          to the famous "dragon gates," great openings left in buildings so
          that, as local belief holds, dragons can pass from the mountains
          to the sea. The Bank of China Tower's sharp, angular form was
          widely discussed in the city in feng shui terms when it rose in
          the late 1980s, and neighbouring buildings were reportedly
          adjusted in response. Whether one reads such stories as
          superstition or as local culture in action, they show how deeply
          feng shui remains woven into the life of a modern city.
        </p>
      </section>

      <!-- 现代视角 -->
      <section class="section">
        <h2 class="section-title">Feng Shui in the Modern World</h2>
        <p class="section-text">
          Feng shui today lives a double life. In China it is both a living
          folk tradition — families still consult masters before building,
          moving, or opening a shop — and a global design trend, taught in
          weekend courses and applied in offices and hotels from London to
          Los Angeles. During the 20th century it was discouraged on the
          mainland as superstition, yet it never disappeared, surviving in
          Taiwan, Hong Kong, and overseas Chinese communities, and returning
          openly in recent decades.
        </p>
        <p class="section-text">
          Scientists are clear on one point: there is no scientific
          evidence for qi as a measurable energy, or for the idea that a
          compass direction determines a person's fortune. But researchers
          and architects also note that many feng shui rules overlap with
          what environmental psychology and good design already recommend:
          natural light, fresh air, views of nature, clear paths through a
          room, a sheltered back and an open front. A home arranged by
          feng shui principles often simply feels better to live in — and
          that feeling is real, whatever its cause.
        </p>
        <p class="section-text">
          Perhaps that is why feng shui has lasted so long. It is not only
          a set of rules about luck; it is a reminder to pay attention to
          the places we live in — to light and air, to the land outside the
          window, to the feeling of shelter and openness. Long before
          modern design spoke of wellbeing and sustainability, feng shui
          was asking the same question: how should a house sit in the
          world, so that the people inside it can thrive?
        </p>
      </section>

