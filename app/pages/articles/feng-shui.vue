      <section class="section">
        <h2 class="section-title">Wind and Water: What the Name Means</h2>
        <p class="section-text">
          The name itself is a piece of philosophy. Wind cannot be seen or
          held, and water is always moving; together they stand for the
          invisible forces that shape a place. A good site, in feng shui
          terms, is one where the wind is gentle rather than harsh and the
          water gathers rather than rushes away. The classic image is a
          house with a mountain at its back — shelter from cold winds — and
          a curving river or pond in front, where water, and with it good
          fortune, can pool.
        </p>
        <p class="section-text">
          At the centre of the system is <em>qi</em>, the energy that in
          Chinese thought animates everything from the human body to the
          weather. Feng shui is the art of letting qi flow smoothly through
          a place: not too fast, like a wind tunnel, and not blocked, like
          a dammed stream. A straight road rushing at a front door, for
          example, is said to bring qi too quickly and harshly; a winding
          path slows it down. A cluttered, dark room is said to trap qi; an
          open, well-lit one lets it circulate. Much of feng shui can be
          read as a language for talking about flow, light, air, and
          shelter — things every builder and homemaker has always cared
          about.
        </p>
        <p class="section-text">
          Two other ideas run through the whole system. One is the balance
          of <em>yin and yang</em> — dark and light, stillness and movement,
          softness and firmness — which should be kept in proportion in any
          space. The other is the <em>five elements</em> — wood, fire,
          earth, metal, and water — which are said to nourish or restrain
          each other in a cycle. A room that is all hard surfaces and sharp
          corners, for instance, might be softened with wood and plants.
          To learn more about these foundations, see our articles on
