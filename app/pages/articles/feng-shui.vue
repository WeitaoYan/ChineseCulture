      <section class="section">
        <h2 class="section-title">The Bagua: A Map of Eight Directions</h2>
        <p class="section-text">
          The <em>bagua</em> (八卦, "eight trigrams") is the map feng shui
          masters lay over a home or a piece of land. It is an octagon
          divided into eight sections, each tied to a direction, an element,
          and an area of life — wealth, reputation, love and marriage,
          family, health, children and creativity, knowledge, and helpful
          people and travel. At its centre lies the taiji, the yin-yang
          symbol, representing balance itself.
        </p>
        <p class="section-text">
          The bagua comes from the <em>Book of Changes</em> (I Ching), one
          of China's oldest texts, where the eight trigrams are built from
          combinations of broken (yin) and solid (yang) lines. In feng
          shui practice, the map is aligned with the compass directions of
          a house, so that each corner of the home corresponds to one area
          of life. A dark, neglected corner in the wealth area, for
          example, might be brightened with a lamp or a healthy plant; a
          cluttered entrance in the "helpful people" area might be cleared
          to make room for new connections.
        </p>
        <p class="section-text">
          Modern practitioners use two versions of the map. The
          traditional compass bagua is aligned to the actual compass
          directions of the house. The simpler "Western" or Black Hat
          version, popular outside China since the late 20th century,
          aligns the map to the front door instead. Traditional masters
          consider the compass version the authentic one; the door-based
          version is a modern simplification that has made feng shui
          accessible to beginners around the world.
        </p>
      </section>

      <!-- 罗盘 -->
      <section class="section">
        <h2 class="section-title">The Luopan: The Feng Shui Compass</h2>
        <p class="section-text">
          The feng shui master's most important tool is the
          <em>luopan</em> (罗盘), a compass unlike any used at sea. At its
          centre is a magnetic needle floating in a pool of water; around
          it, ring upon ring of inscriptions — the twenty-four directions,
          the trigrams, the five elements, the stems and branches of the
          Chinese calendar, and more. Some luopan have a dozen or more
          concentric rings, each one a layer of knowledge the master must
          read together.
        </p>
        <p class="section-text">
          The luopan was developed during the Song dynasty (960–1279),
          when the magnetic compass — itself a Chinese invention — was
          adapted for feng shui use. With it, a master could measure the
          exact facing direction of a house or a grave down to a fraction
          of a degree, and judge whether it matched the birth dates of the
          people who would live there. A direction that suited one person
          might, in the compass school's calculations, be unlucky for
          another — which is why traditional feng shui is always personal,
          tied to the people in the house as much as to the house itself.
        </p>
        <p class="section-text">
          Today the luopan remains the symbol of the profession. Even
          masters who use smartphone compass apps still keep a brass luopan
          for consultations, and its rings of characters have become one of
          the most recognizable images of Chinese traditional culture.
        </p>
      </section>

