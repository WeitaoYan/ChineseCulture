      <section class="section">
        <h2 class="section-title">The Five Elements in a Room</h2>
        <p class="section-text">
          The five elements — wood, fire, earth, metal, and water — are
          the basic vocabulary of feng shui. Each is linked to a direction,
          a season, a colour, and a quality, and each is said to feed the
          next in a generating cycle (wood feeds fire, fire creates earth,
          earth bears metal, metal carries water, water nourishes wood)
          while restraining another. Balancing a space means making sure no
          element overwhelms the rest:
        </p>
        <FeatureGrid>
          <FeatureItem title="🌳 Wood (木)" theme="green">
            <p>
              Growth, vitality, and new beginnings. Wood is represented by
              plants, wooden furniture, and the colours green and brown. It
              suits studies and places of work, and is said to encourage
              creativity and steady growth.
            </p>
          </FeatureItem>
          <FeatureItem title="🔥 Fire (火)" theme="red">
            <p>
              Warmth, passion, and visibility. Fire appears in candles,
              lamps, and the colours red and orange. A touch of fire is said
              to bring energy and recognition; too much is believed to make
              a room restless and tense.
            </p>
          </FeatureItem>
          <FeatureItem title="⛰️ Earth (土)" theme="gold">
            <p>
              Stability, nourishment, and grounding. Earth is found in
              ceramics, stone, and yellow or sandy tones. It is the element
              of the centre of the home, and is said to steady a household
              that feels unsettled.
            </p>
          </FeatureItem>
          <FeatureItem title="⚙️ Metal (金)" theme="gray">
            <p>
              Clarity, precision, and order. Metal shows itself in round
              shapes, white and grey colours, and metal objects. It is
              linked to clear thinking and is often used to calm a space
              that feels chaotic or overcrowded.
            </p>
          </FeatureItem>
          <FeatureItem title="💧 Water (水)" theme="blue">
            <p>
              Flow, reflection, and abundance. Water is represented by
              mirrors, glass, fountains, and the colours blue and black.
              Flowing water is said to draw in wealth and opportunity — one
              reason ponds and aquariums are classic feng shui features.
            </p>
          </FeatureItem>
          <FeatureItem title="☯️ Yin and Yang" theme="yellow">
            <p>
              Above the elements sits the balance of yin and yang. A living
              room should be more yang — bright, open, active — while a
              bedroom should be more yin — dim, quiet, restful. A home where
              every room feels the same, practitioners say, is a home out of
              balance.
            </p>
          </FeatureItem>
        </FeatureGrid>
