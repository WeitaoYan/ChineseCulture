      <section class="section">
        <h2 class="section-title">Overview</h2>
        <p class="section-text">
          <strong>Feng shui</strong> (风水, Fēng Shuǐ) literally means
          "wind and water." It is China's ancient system for reading the
          landscape — and arranging homes, graves, temples, and whole cities
          — so that people live in harmony with the forces around them.
          Practitioners believe that a vital energy called
          <em>qi</em> (气) flows through the land, and that the shape of
          mountains, the course of rivers, and the direction a door faces
          can gather good qi or let it slip away.
        </p>
        <p class="section-text">
          To outsiders, feng shui is often reduced to furniture tips and
          lucky ornaments. In China it is much older and much larger than
          that. For well over a thousand years it guided where emperors
          built their capitals, where families buried their ancestors, and
          where farmers placed their houses. Its ideas grew out of the same
          soil as Daoism, the <em>Book of Changes</em> (I Ching), and
          traditional Chinese medicine: the belief that the world runs on
          patterns, that everything is connected, and that human life goes
          best when it moves with those patterns rather than against them.
        </p>
        <p class="section-text">
          Today feng shui is still consulted across China and the wider
          Chinese-speaking world — and increasingly by architects and
          homeowners far beyond it. Whether or not one believes in qi, the
          questions feng shui asks are familiar to anyone who has ever
          chosen a home: Is there light? Is there fresh air? Does the place
          feel sheltered, or exposed? Does it feel calm? Feng shui is, at
          heart, one of the oldest answers to those questions.
        </p>
      </section>

