        <h2 class="section-title">Hotpot at Its Source</h2>
        <p class="section-text">
          No account of Chongqing is complete without its food, and no food
          matters more here than hotpot. The city's version — a bubbling pot
          of broth loaded with chilli and Sichuan pepper, into which diners
          cook thin slices of meat, vegetables and offal — grew up in the
          19th century among Yangtze boatmen and dock workers, who needed a
          cheap, hot, communal meal after long days on the river. The
          numbing-spicy <em>mala</em> (麻辣) flavour that defines it is
          Chongqing's gift to Chinese cuisine, and the city still treats
          hotpot as an everyday meal rather than an occasion: there are
          thousands of hotpot restaurants here, from riverside terraces to
          tiny neighbourhood shops where the broth has been simmering for
          years.
        </p>
        <p class="section-text">
          The rules are simple: order a <em>yuanyang</em> (鸳鸯, mandarin
          duck) pot if your group is mixed — one side spicy, one side mild —
          cook thin items for seconds and thick ones for minutes, and keep a
          bowl of sesame oil and garlic to cool each mouthful. Beyond hotpot,
          try the city's noodles: <strong>Chongqing xiaomian</strong> (重庆小面),
          small bowls of wheat noodles in a spicy, peanut-sesame sauce, sold
          from street stalls for breakfast. For the full history of hotpot —
          its origins, its rituals and how it spread across China — see our
          article on
          <NuxtLink to="/articles/chinese-hotpot">Chinese hotpot</NuxtLink>.
        </p>
      </section>

