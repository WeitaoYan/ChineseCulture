      <section class="section">
        <h2 class="section-title">Hongyadong: The Cliffside City of Light</h2>
        <p class="section-text">
          The single image that made Chongqing famous is
          <strong>Hongyadong</strong> (洪崖洞), a cluster of traditional
          stilted wooden houses — <em>diaojiaolou</em> (吊脚楼), built on
          stilts against the cliff — stacked eleven storeys high above the
          Jialing River in the Jiefangbei district. By day it is a warren of
          shops, snack stalls and viewpoints in the Bayu folk style, modelled
          on the cliff dwellings that once lined this riverbank. After dark
          it becomes something else entirely: thousands of golden lights
          switch on across the whole cliff face, and the building looks like
          a glowing palace floating above the water. It is routinely compared
          to the bathhouse in the animated film <em>Spirited Away</em>, and
          the resemblance is hard to deny.
        </p>
        <p class="section-text">
          A few tips for the visit. Hongyadong has entrances on several
          different levels, and the "ground floor" you enter from the street
          may be the 11th floor of the complex — ask for directions, and do
          not be surprised to leave by a road that runs across the roof. The
          best views are from across the river: walk down to the riverside
          promenade, or cross to the far bank at dusk and watch the lights
          come on. Go on a weekday evening if you can; at weekends and on
          holidays the complex can be so crowded that the stairways slow to
          a shuffle. And do not skip the food stalls inside — this is one of
          the easiest places in the city to graze your way through Chongqing
          snacks in a single evening.
        </p>
        <p class="section-text">
          From Hongyadong it is a short walk to <strong>Jiefangbei</strong>
          (解放碑), the downtown square built around a wartime monument, and
          to the riverside at <strong>Chaotianmen</strong> (朝天门), the
          pointed peninsula where the Jialing flows into the Yangtze — the
          best place in the city to see the two rivers meet, and the
          departure point for Yangtze River cruises downstream through the
          Three Gorges.
        </p>
      </section>

