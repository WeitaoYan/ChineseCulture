              five-minute ride is the best cheap view in the city — river,
              bridges and the whole stacked skyline at once.
            </p>
          </FeatureItem>
          <FeatureItem title="🌃 Two Rivers Night View" theme="blue">
            <p>
              Take the evening cruise from Chaotianmen, or watch from Nanshan
              Mountain on the south bank, where the whole of Yuzhong lights
              up across the river. Chongqing's skyline is at its best after
              dark, when the layers of the city turn into layers of light.
            </p>
