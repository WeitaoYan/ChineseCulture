        <p class="section-text">
          Chongqing's summers are famously hot — it is one of China's
          "furnace cities" — and its winters are damp and grey. Spring and
          autumn are the most comfortable times to visit, and the city is at
          its most atmospheric in the misty months. Whatever the season,
          bring comfortable shoes: this is a city of stairs.
        </p>
        <FeatureGrid>
          <FeatureItem title="🌸 Best Time to Visit" theme="green">
            <p>
              March–May and September–November offer the mildest weather.
              Summer brings heat and sudden downpours; winter is mild but
              cloudy and foggy. The Hongyadong lights and the river views
              are at their best on clear evenings after rain.
            </p>
          </FeatureItem>
          <FeatureItem title="🚇 Getting Around" theme="blue">
            <p>
              The metro is the easiest way to move — Lines 1, 2, 3 and 6
              cover Hongyadong, Liziba, Ciqikou and the railway stations.
              Buses and ride-hailing fill the gaps, but remember that
              distances on the map hide large changes in height.
            </p>
          </FeatureItem>
          <FeatureItem title="🗓️ How Long to Stay" theme="gold">
            <p>
              Two to three days is enough for the city itself: one day for
              Hongyadong, Jiefangbei and the river, one day for Liziba,
              Ciqikou and the cableway. Add days for a Three Gorges cruise
              or a trip to Dazu or Wulong.
            </p>
          </FeatureItem>
          <FeatureItem title="💳 Money and Phones" theme="gray">
            <p>
              Mobile payment is the norm — set up Alipay or WeChat Pay with
              a foreign card before you arrive. Carry your passport for
              train tickets and cruise bookings, and download an offline
              map: the vertical streets confuse even good navigation apps.
            </p>
          </FeatureItem>
        </FeatureGrid>
