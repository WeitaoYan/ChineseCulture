        <h2 class="section-title">
          Liziba and the 8D City: A Monorail Through a Building
        </h2>
        <p class="section-text">
          Chongqing's second viral landmark is a train station inside a block
          of flats. At <strong>Liziba</strong> (李子坝), on Metro Line 2, the
          monorail passes directly through a 19-storey residential building —
          the track runs through the 6th to 8th floors, with the station
          itself built into the structure. Residents live above and below the
          trains, which glide past their windows every few minutes. It was
          not a stunt: when the line was planned, the city and the building's
          developers agreed to share the space rather than demolish the
          block, and the station became the most photographed metro stop in
          China.
        </p>
        <p class="section-text">
          Liziba is the perfect introduction to what locals mean by the
          <strong>8D city</strong>. Chongqing is built on hills so steep
          that the usual rules of a city do not apply: a road can be a
          bridge, a bridge can have shops on it, and the square outside one
          building's front door is the roof of another. Navigation apps
          struggle here — a destination 100 metres away on the map can be
          twenty floors above you. Visitors learn quickly to navigate by
          landmarks rather than addresses, and to ask locals which floor the
          street they want is on.
        </p>
        <FeatureGrid>
          <FeatureItem title="🚝 Liziba Station" theme="gold">
            <p>
