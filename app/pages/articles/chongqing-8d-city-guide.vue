        <p class="section-text">
          Chongqing is the gateway to some of China's great landscapes, and
          it rewards travellers who leave the city for a day or two:
        </p>
        <FeatureGrid>
          <FeatureItem title="🏞️ The Three Gorges" theme="blue">
            <p>
              Yangtze cruises depart from Chaotianmen and sail downstream
              through the Qutang, Wu and Xiling Gorges — sheer cliffs, mist
              and the Three Gorges Dam. Trips run from three to five days to
              Yichang, and shorter day cruises cover the nearest gorge
              scenery.
            </p>
          </FeatureItem>
          <FeatureItem title="🗿 Dazu Rock Carvings" theme="gold">
            <p>
              About two hours west of the city, the Dazu carvings are a
              UNESCO World Heritage site: tens of thousands of Buddhist,
              Daoist and Confucian figures carved into the cliffs from the
              Tang to the Song dynasties, circa 7th–13th century. The
              reclining Buddha at Baodingshan is the highlight.
            </p>
          </FeatureItem>
          <FeatureItem title="⛰️ Wulong Karst" theme="green">
            <p>
              Two to three hours southeast, Wulong's karst landscape — giant
              natural stone bridges, sinkholes and caves — is part of the
              South China Karst UNESCO site. It is the most dramatic scenery
              within easy reach of the city, and the setting for several
              well-known Chinese films.
            </p>
          </FeatureItem>
        </FeatureGrid>
