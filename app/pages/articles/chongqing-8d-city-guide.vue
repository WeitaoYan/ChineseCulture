      <section class="section">
        <h2 class="section-title">Old Towns and Wartime History</h2>
        <p class="section-text">
          Behind the viral landmarks, Chongqing is an old river city with a
          distinct <strong>Bayu culture</strong> — the culture of the ancient
          Ba people who lived along these rivers more than 2,000 years ago.
          The best place to feel it is <strong>Ciqikou Ancient Town</strong>
          (磁器口), a former porcelain-trading port on the Jialing River
          whose Ming- and Qing-dynasty streets are lined with teahouses,
          craft shops and snack stalls. It is touristy, and it is also
          genuinely old: the town's lanes, temples and riverside steps have
          been in use for centuries, and the morning, before the crowds
          arrive, still belongs to the locals.
        </p>
        <p class="section-text">
          Chongqing also carries the weight of modern Chinese history. From
          1937, during the war against Japan, it served as China's wartime
          capital, and the city was heavily bombed — the air-raid shelters
          carved into its hillsides are still visible today. The
          <strong>Huguang Guild Hall</strong> (湖广会馆) in Yuzhong, a
          riverside complex of guild halls built by migrants from other
          provinces in the Qing dynasty, is one of the finest surviving
          pieces of old Chongqing, with carved wooden theatres and courtyards
          that now host folk performances. For a quieter hour, climb to
          <strong>Eling Park</strong> (鹅岭公园), the city's oldest park, for
          a panoramic view over the two rivers and the layered rooftops.
        </p>
        <p class="section-text">
          Chongqing's other nickname is the <strong>"Fog City"</strong>
          (雾都) — the river valleys fill with mist on many mornings, and
          the city has a famously damp, overcast winter. The fog softens the
          hard edges of the concrete and makes the night lights glow; it is
          part of the city's atmosphere, and a good excuse for another pot
          of tea.
        </p>
      </section>

