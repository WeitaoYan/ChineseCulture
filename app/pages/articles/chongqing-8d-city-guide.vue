          Chongqing pairs naturally with Chengdu: the two cities are about
          two hours apart by high-speed train, and most first-time visitors
          to Sichuan see both. Chengdu is the city to slow down in;
          Chongqing is the city to look up in — preferably at night, from
          across the river, when the whole 8D puzzle lights up at once.
        </p>
