        <h2 class="section-title">Overview</h2>
        <p class="section-text">
          <strong>Chongqing</strong> (重庆) is the city that broke the map.
          Built on steep hills where the Yangtze and Jialing Rivers meet in
          southwestern China, it is a place where roads run on rooftops,
          bridges cross over apartment blocks, and a train passes through the
          middle of a residential building. Locals joke that in Chongqing the
          ground floor of one building is the twentieth floor of the one next
          door — and they are only slightly exaggerating. Chinese social media
          calls it the <strong>"8D city"</strong>: a city with so many
          vertical layers that two dimensions are not enough to describe it.
        </p>
        <p class="section-text">
          For years Chongqing was the overlooked neighbour of Chengdu, two
          hours away by high-speed train. That changed in 2026. In the first
          half of the year, inbound flights to Chongqing rose 30% — the
          fastest growth of any city in China's Top 10 — and inbound visitors
          were up roughly 170% year on year in early 2026, with overnight
          international visitors up 52.1% over the Spring Festival holiday
          alone. Short videos of the monorail, the cliffside lights of
          Hongyadong and the city's impossible geometry have made Chongqing
          one of the most viral destinations in China.
        </p>
        <p class="section-text">
          This guide is about the city itself: its stacked streets, its river
