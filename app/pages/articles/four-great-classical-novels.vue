          <em>Journey to the West</em> is the most fantastical of the four —
          and the most beloved by children. It begins with a stone monkey born
          on the Mountain of Flowers and Fruit, who trains in magic, steals
          the heavenly peaches, and rebels against Heaven itself before the
          Buddha traps him under a mountain for five hundred years. Freed by
          the monk Xuanzang, Sun Wukong (孙悟空) becomes the monk's disciple
          and protector on the long journey to India to fetch Buddhist
          scriptures.
        </p>
        <p class="section-text">
          The travellers make an unforgettable team: Sun Wukong, the clever
          trickster with his golden-banded staff and cloud-somersault; Zhu
          Bajie (猪八戒), the greedy, lazy pig demon who is always hungry and
          always funny; Sha Wujing (沙悟净), the quiet, steady former general;
          and the White Dragon Horse who carries their luggage. Along the road
          they face 81 trials — demons, temptations, and disasters — each one
          a test of patience, discipline, and faith.
        </p>
        <p class="section-text">
          Behind the comedy is a real journey. The monk Xuanzang (玄奘) really
          did travel to India in the 7th century, leaving Chang'an in 629 CE
          and returning in 645 CE with hundreds of Buddhist texts. The novel
          turns that sixteen-year pilgrimage into a story about growth: the
          Monkey King begins as a rebel who wants only freedom and ends as a
          Buddha — the journey itself is the transformation.
        </p>
      </section>

