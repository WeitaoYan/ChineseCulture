        <h2 class="section-title">Romance of the Three Kingdoms (三国演义)</h2>
        <p class="section-text">
          When the Han dynasty collapsed in the 3rd century, China split into
          three rival states: Wei, Shu, and Wu. <em>Romance of the Three
          Kingdoms</em> turns that century of warfare into one of the world's
          great historical novels, blending the official history
          <em>Records of the Three Kingdoms</em> (三国志), written by Chen Shou
          in the 3rd century, with centuries of folk tales and stage plays.
        </p>
        <p class="section-text">
          The novel opens with one of the most famous scenes in Chinese
          literature: Liu Bei, Guan Yu, and Zhang Fei swearing brotherhood in a
          peach garden, promising to live and die together. Around them move
          figures who have become models of character in Chinese culture —
          Zhuge Liang, the strategist whose wisdom seems almost supernatural;
          Cao Cao, the brilliant and ruthless warlord; and Guan Yu, whose
          loyalty is so revered that he was later worshipped as a god of war.
        </p>
        <p class="section-text">
          Its great set pieces are still retold today: the Battle of Red Cliffs
          (208 CE), where a smaller force defeats a vast army with fire ships;
          the Empty Fort Strategy, where Zhuge Liang bluffs an enemy army away
          with nothing but an open gate and a lute; and the long, doomed
          northern campaigns of a kingdom that knows it cannot win. The novel's
          opening line has become a proverb in itself: "The empire, long
          divided, must unite; long united, must divide."
        </p>
      </section>

