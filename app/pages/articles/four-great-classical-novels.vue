      <section class="section">
        <h2 class="section-title">Water Margin (水浒传)</h2>
        <p class="section-text">
          <em>Water Margin</em> begins with ordinary men driven to the edge by
          corrupt officials — and follows them to Liangshan Marsh, a watery
          stronghold in today's Shandong Province where 108 outlaws gather
          under the banner of justice. Each of the 108 corresponds to a star
          of destiny, and each arrives with a story of how society failed
          them: Lin Chong, the honest arms instructor framed by a powerful
          minister; Wu Song, who kills a tiger with his bare hands and later
          avenges his brother; Lu Zhishen, the rough monk with a heart of
          gold.
        </p>
        <p class="section-text">
          The novel's heroes are not polished gentlemen. They drink, brawl,
          and break the law — but they do so by a code: they rob the corrupt
          and protect the weak, and they prize brotherhood above all. Their
          rallying cry, "替天行道" — "to carry out the Way on behalf of
          Heaven" — captures the novel's central tension: when the law itself
          is unjust, is rebellion a crime or a duty?
        </p>
        <p class="section-text">
          That question is why the book has been both loved and feared. For
          centuries, storytellers performed its episodes in teahouses and
          marketplaces; at times, officials banned it as dangerous. Its
          ending is famously bittersweet: the outlaws accept an imperial
          amnesty and go to fight for the state, and most of them die — a
          reminder that in this world, even heroes cannot escape fate.
        </p>
      </section>

