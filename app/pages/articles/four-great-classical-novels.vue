          In modern times, television made them bigger still. The 1980s
          television adaptations of <em>Journey to the West</em> and
          <em>Dream of the Red Chamber</em> were watched by hundreds of
          millions of viewers, and new versions appear in every decade — along
          with films, cartoons, video games, and comics. Sun Wukong has become
          a global pop-culture figure, while Zhuge Liang's feather fan and
          Guan Yu's long beard are visual shorthand for wisdom and loyalty.
        </p>
        <p class="section-text">
          Perhaps their deepest legacy is in the language itself. Chinese
          everyday speech is full of phrases from these books: "speak of Cao
          Cao and he appears" (说曹操，曹操到) for someone who turns up just
          as you mention them; the "empty fort strategy" (空城计) for a bold
          bluff; "three visits to the thatched cottage" (三顾茅庐) for
          sincerely seeking out talent. To know these stories is, in a real
          sense, to speak Chinese.
        </p>
