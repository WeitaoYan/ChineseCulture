          fiction: <em>Romance of the Three Kingdoms</em>,
          <em>Water Margin</em>, <em>Journey to the West</em>, and
          <em>Dream of the Red Chamber</em>. Written between the 14th and 18th
          centuries, they grew out of centuries of oral storytelling, folk
          tales, and stage plays before being shaped into long novels — and
          they have never left Chinese cultural life since.
        </p>
        <p class="section-text">
          Together the four cover almost every kind of story China loves to
          tell: a sweeping war epic, a tale of outlaws and brotherhood, a
          fantastical pilgrimage full of demons and magic, and an intimate
          family saga of love and decline. Their characters — the strategist
          Zhuge Liang, the outlaw Wu Song, the Monkey King Sun Wukong, the
          dreamer Jia Baoyu — are household names, quoted in everyday speech,
          played on opera stages, and reborn in every generation of television,
          film, and games.
        </p>
        <p class="section-text">
          The four are usually grouped together because each one did something
          new for Chinese literature. The first three were written mostly in
          vernacular language — the everyday speech of ordinary people — rather
          than the classical Chinese of scholars, which helped them reach an
          enormous audience. The fourth, <em>Dream of the Red Chamber</em>,
          took the novel to a new height of psychological depth. For anyone
          who wants to understand Chinese culture, these four books are the
          place to start.
        </p>
