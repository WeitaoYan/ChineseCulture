        <h2 class="section-title">Dream of the Red Chamber (红楼梦)</h2>
        <p class="section-text">
          <em>Dream of the Red Chamber</em> is unlike the other three. There
          are no great battles and no demons — only a great family, the Jias,
          and the young people growing up inside its walled gardens. At its
          heart is a love triangle: Jia Baoyu (贾宝玉), the sensitive young
          heir born with a piece of jade in his mouth; Lin Daiyu (林黛玉),
          the brilliant, fragile poet who is his true love; and Xue Baochai
          (薛宝钗), the graceful, sensible cousin his family wants him to
          marry.
        </p>
        <p class="section-text">
          Cao Xueqin (曹雪芹) wrote from life. His own family had been wealthy
          and close to the imperial court before falling into ruin, and the
          novel is, among other things, a portrait of that world — its
          poetry parties and birthday feasts, its servants and schemes, its
          beauty and its cruelty — and a record of how it all slips away. The
          Grand View Garden (大观园), built for a visit by an imperial
          concubine, is the novel's paradise: a place of poetry and youth
          that cannot last.
        </p>
        <p class="section-text">
          The novel is so rich that an entire field of study grew up around
          it: "Redology" (红学), the scholarship of <em>Dream of the Red
          Chamber</em>. Readers debate its riddles, its prophecies, and its
          ending — Cao Xueqin died before finishing it, and the last 40
          chapters were completed later, traditionally attributed to Gao E.
          Its opening warning still frames the whole book: "Truth becomes
          fiction when the fiction's true" — in this dream of red mansions,
          nothing is quite what it seems.
        </p>
      </section>

