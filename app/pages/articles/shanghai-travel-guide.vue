          travellers — and the first half of 2026 added another 5.31 million
          overseas visitors, up 27.8%. For most visitors, Shanghai is not a
          detour; it is the front door. The city rewards that role well: it is
          the easiest place in China to arrive in, to get around in, and to
          start understanding the country from — and three days are enough to
          see both of its faces properly.
        </p>
        <p class="section-text">
