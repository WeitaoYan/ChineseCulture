        <h2 class="section-title">Overview</h2>
        <p class="section-text">
          <strong>Shanghai</strong> (上海, Shànghǎi) is the first China most
          travellers ever meet — and the strangest. Stand on the Bund at dusk
          and you can see two centuries at once: on your side of the Huangpu
          River, a row of granite banks and hotels built when Shanghai was the
          busiest treaty port in Asia; across the water, the twisted glass of
          the Shanghai Tower and the twin spheres of the Oriental Pearl Tower,
          the skyline of a city that rebuilt itself in a single generation.
          Few places on earth compress that much history into one view.
        </p>
        <p class="section-text">
          The numbers match the first impression. Shanghai welcomed
          <strong>9.36 million inbound visitors in 2025, up 39.6%</strong> on
