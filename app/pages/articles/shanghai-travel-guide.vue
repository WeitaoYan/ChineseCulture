      <section class="section">
        <h2 class="section-title">The Old City &amp; Yu Garden (豫园)</h2>
        <p class="section-text">
          Ten minutes south of the Bund, the city changes character
          completely. The Old City (老城厢) is what Shanghai was before the
          concessions: a tight maze of lanes around the City God Temple
          (城隍庙), where gold shops, tea houses, and snack stalls crowd
          shoulder to shoulder. It is loud, crowded, and gloriously
          unpolished — the Shanghai that most postcards leave out.
        </p>
        <p class="section-text">
          At its heart is <strong>Yu Garden</strong> (豫园), a classical
          garden built in the Ming dynasty by a local official for his
          parents. Inside its walls are zigzag bridges, a famous rockery
          built from porous Taihu stone, carp ponds, and pavilions with
          names like the Hall of Spring — a pocket of stillness that has
          survived four centuries of everything Shanghai threw at it. Go
          early in the morning to have the garden almost to yourself, then
          step outside into the bazaar for the full contrast.
        </p>
        <p class="section-text">
          Eat here, too. The Old City is the home of Shanghai's most famous
          snack, <em>xiaolongbao</em> (小笼包) — soup dumplings pinched shut
          at the top and eaten with a spoonful of black vinegar and ginger.
          The queues at the famous shops look intimidating but move fast, and
          a basket of dumplings with a pot of tea is one of the cheapest good
          meals in the city. For the full story of the dumpling itself, see
          our guide to Chinese dumplings; here, just eat them where they were
          invented.
        </p>
      </section>

