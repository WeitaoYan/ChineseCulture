      <section class="section">
        <h2 class="section-title">The Former French Concession: Shanghai at Walking Pace</h2>
        <p class="section-text">
          West of the Old City lies the former French Concession, the
          district the French administered from 1849 until the 1940s, and
          today the most walkable neighbourhood in Shanghai. Its streets are
          lined with plane trees, low brick villas, and wrought-iron gates —
          a European garden suburb that somehow became the city's most
          Chinese neighbourhood, full of noodle shops, wet markets, and old
          men playing chess on the pavement.
        </p>
        <p class="section-text">
          The best way to see it is to pick a street and wander. Wukang Road
          (武康路) has the famous wedge-shaped Wukang Building and a row of
          historic villas; Tianzifang (田子坊) is a warren of converted
          <em>shikumen</em> (石库门) lane houses — the brick-and-stone
          courtyard homes that once housed most of Shanghai — now filled with
          craft shops, cafés, and tiny galleries; Xintiandi (新天地) is the
          polished, rebuilt version of the same idea, where restored lane
          houses hold restaurants and bars around a car-free plaza.
        </p>
        <p class="section-text">
          The Concession is also where Shanghai's café culture lives. The
          city drinks more coffee than almost anywhere else in China, and the
          small roasteries and old-house cafés here are a good place to sit
          out the afternoon heat — or the rain — with a book. Slow down here
          on purpose: after the Bund and the Old City, the Concession is the
          part of Shanghai that asks you to stop rushing.
        </p>
      </section>

      <!-- 陆家嘴 -->
      <section class="section">
        <h2 class="section-title">Lujiazui (陆家嘴): The Future, Across the River</h2>
        <p class="section-text">
          Cross the river — by metro, by ferry, or through the Bund Sightseeing
          Tunnel — and you are in Lujiazui, the financial district built on
          Pudong farmland after 1990. Three towers dominate it, and each
          tells a different part of the story: the Oriental Pearl Tower
          (东方明珠塔), completed in 1994, with its two giant pink spheres,
          was the symbol of the new Shanghai before it was even finished; the
          Jin Mao Tower (金茂大厦) stacks like a pagoda in glass and steel;
          and the Shanghai Tower (上海中心大厦), at 632 metres, is the
          tallest building in China and the second tallest in the world, its
          twisting form designed to shrug off typhoon winds.
        </p>
        <p class="section-text">
          The Shanghai Tower's observation deck, more than 550 metres up, is
          the highest in the world — on a clear day you can see the whole
          curve of the Huangpu and the old city laid out like a map. The
          Oriental Pearl's glass-floored deck, by contrast, lets you look
          straight down 259 metres to the street. Pick one tower per visit;
          both are worth it, neither is cheap, and prices vary by season, so
          check the official ticketing pages before you go.
        </p>
        <p class="section-text">
          At ground level, Lujiazui is all polished malls and office lobbies
          — impressive, but less human than the west bank. The best view of
          it is still the one from the Bund, at night, when the whole
          skyline lights up and the river doubles it. If you only do one
          evening in Shanghai, spend it watching that reflection.
        </p>
      </section>

