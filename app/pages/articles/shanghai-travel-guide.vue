      <section class="section">
        <h2 class="section-title">The Bund (外滩): One Street, Two Centuries</h2>
        <p class="section-text">
          The Bund is a 1.5-kilometre promenade along the west bank of the
          Huangpu River, and it is the single essential stop in Shanghai. The
          buildings facing the river — some fifty grand structures in
          neoclassical, Art Deco, Gothic, and Baroque styles — were mostly
          built between the 1900s and the 1930s, when this was the Wall Street
          of the Far East. The most famous are the domed HSBC Building (now
          the Pudong Development Bank), the former Customs House with its
          clock tower modelled on London's Big Ben, and the Peace Hotel, whose
          green pyramid roof has watched over the waterfront since 1929.
        </p>
        <p class="section-text">
          Come twice if you can: once in the morning, when the promenade
          belongs to tai chi practitioners and the light is kind to the stone
          facades, and once after dark, when the buildings are floodlit and
          the towers across the river switch on. The river itself is part of
          the show — a working waterway full of barges and ferries — and a
          short Huangpu River cruise at dusk is the easiest way to see both
          banks at once. Ticket prices and cruise times change with the
          season, so check the official channels before you go.
        </p>
        <p class="section-text">
          Behind the promenade, Nanjing Road runs east to west — one of the
          world's busiest shopping streets, a noisy river of neon, department
          stores, and snack stalls that has been Shanghai's main street for
          more than a century. Walk it once for the spectacle; shop elsewhere
          for better prices.
        </p>
      </section>

