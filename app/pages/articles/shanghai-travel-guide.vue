        <h2 class="section-title">Practical Tips for First-Timers</h2>
        <p class="section-text">
          <strong>Getting around.</strong> Shanghai's metro is one of the
          largest in the world, with English signage everywhere and fares
          that rarely exceed a few yuan. Buy a transport card or use your
          phone's wallet; taxis are plentiful and cheap by international
          standards, and ride-hailing apps work well. The two airports —
          Pudong (PVG) and Hongqiao (SHA) — are both connected by metro, and
          the Maglev train from Pudong Airport still runs at up to 300
          km/h on its short dash into the city.
        </p>
        <p class="section-text">
          <strong>Paying.</strong> Like the rest of China, Shanghai runs on
          mobile payment — Alipay and WeChat Pay accept most foreign cards
          now — but cash is still accepted in most places, and the metro and
          major attractions take cards. Set up a payment app before you
          arrive; it saves a queue at every ticket window.
        </p>
        <p class="section-text">
          <strong>When to go.</strong> Spring (April–May) and autumn
          (September–October) are the most comfortable, with warm days and
          clear skies. Summer is hot and humid, winter is damp and chilly
          rather than freezing. Avoid the first week of October (National Day
          holiday) and the May Day holiday unless you enjoy crowds — the Bund
          on a public holiday is an experience, but not a relaxing one.
        </p>
        <p class="section-text">
          <strong>How long to stay.</strong> Three days covers the city; five
          gives you the day trips and a slower pace. Shanghai also makes a
          natural first or last stop on a longer China trip — it is the
          country's best-connected city, with high-speed trains to Beijing
          (about 4.5 hours), Hangzhou, Suzhou, and Nanjing, and flights to
          everywhere else.
        </p>
