      <section class="section">
        <h2 class="section-title">From Fishing Village to World Port</h2>
        <p class="section-text">
          Shanghai's rise was fast even by Chinese standards. For most of its
          history it was a modest county town at the mouth of the Yangtze,
          known for fishing, cotton, and salt. Everything changed in the
          1840s, when the Treaty of Nanjing opened the city to foreign trade
          and the British, French, and Americans carved out concession
          districts along the river. Within a few decades the Bund — the
          embanked waterfront the British laid out — had become the financial
          heart of East Asia, lined with the banks, trading houses, and hotels
          of a dozen nations.
        </p>
        <p class="section-text">
          The old Chinese city never went away; it simply carried on behind
          the concessions, around the City God Temple and the garden a Ming
          dynasty official built for his parents. And when the concessions
          ended in the 1940s, the city kept its cosmopolitan habits — its
          cafés, its tailors, its jazz — even through the lean decades that
          followed. The second great leap came in 1990, when the government
          opened Pudong, the farmland across the river, for development. In
          about thirty years a skyline of supertall towers rose on what had
          been rice fields. That is the contrast Shanghai sells today, and it
          is not an exaggeration: the two sides of the river genuinely look
          like two different centuries, and the ferry between them takes five
          minutes.
        </p>
      </section>

