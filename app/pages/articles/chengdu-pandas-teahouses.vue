        <h2 class="section-title">Overview</h2>
        <p class="section-text">
          <strong>Chengdu</strong> (成都), the capital of Sichuan Province in
          southwestern China, is the city that taught China how to slow down.
          It is a metropolis of more than 20 million people that still runs on
          teahouse time: old men playing mahjong under the plane trees,
          ear-cleaners working their quiet trade, and pot after pot of
          covered-bowl tea going cold and being refilled. There is an old
          Chinese saying, <em>少不入川</em> — "the young should not go to
          Sichuan" — because the life here is so comfortable that the young
          might never want to leave.
        </p>
