        <h2 class="section-title">Teahouses and the Art of Slow Living</h2>
        <p class="section-text">
          If the Panda Base is Chengdu's most famous attraction, the teahouse
          is its soul. Chengdu is said to have more teahouses than any other
          city in China, and the ritual is always the same: find a bamboo
          chair, order a <strong>gaiwan</strong> (盖碗) — a lidded bowl of tea
          — and stay for hours. The lid keeps the leaves down and the tea
          warm; when your cup runs low, a waiter with a long-spouted kettle
          appears to top it up, often pouring from a surprising distance with
          a flick of the wrist. One bowl can last an entire afternoon, and
          nobody will hurry you out.
        </p>
        <p class="section-text">
          The best place to experience it is
          <strong>People's Park</strong> (人民公园) in the city centre, and
          in particular the <strong>Heming Teahouse</strong> (鹤鸣茶社), a
          century-old institution beside the park's lake. Here the whole of
          Chengdu's slow life is on display at once: retirees playing mahjong
          and cards, friends chatting over sunflower seeds, calligraphers
          practising with water on the pavement, and ear-cleaners
          (<em>掏耳朵</em>) plying a delicate traditional trade with tiny
          metal instruments — a service you will find in teahouses across
          Sichuan and almost nowhere else. Sit down, order a cup of jasmine or
          local green tea, and watch the city do nothing, beautifully.
        </p>
        <p class="section-text">
          Tea in Chengdu is not a ceremony so much as a way of spending time,
          and it connects directly to the wider story of Chinese tea. For the
          history of tea itself — from its legendary discovery to the six
          major types and the art of the tea ceremony — see our
          <NuxtLink to="/articles/chinese-tea-culture">guide to Chinese tea culture</NuxtLink>.
          In the evenings, some of the city's old teahouses also stage
          Sichuan opera, famous for its face-changing
          (<em>变脸</em>), in which performers switch painted masks in the
          blink of an eye — a fitting end to a slow day.
        </p>
      </section>

