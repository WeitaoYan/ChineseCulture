        <h2 class="section-title">What to Eat (Beyond Hotpot)</h2>
        <p class="section-text">
          Chengdu's food goes far beyond its most famous export. Start with
          the everyday classics: <strong>mapo tofu</strong> (麻婆豆腐), the
          numbing-spicy bean curd dish invented here in the 19th century;
          <strong>dan dan noodles</strong> (担担面), thin noodles in a
          chilli-and-Sichuan-pepper sauce; and <strong>kung pao chicken</strong>
          (宫保鸡丁), which is hotter and more numbing in its home city than
          in any takeaway version abroad. The key flavour is
          <em>mala</em> (麻辣) — the tingling numbness of Sichuan pepper
          combined with chilli heat — and it appears in almost everything.
          Street snacks are a meal in themselves around Jinli and the Wide
          and Narrow Alleys: try rabbit heads and duck necks only if you are
          feeling brave, and save room for the city's sweet side, like brown
          sugar glutinous rice cakes. Hotpot, of course, is everywhere in
          Chengdu — but it gets exactly one sentence here, because it already
          has its own article:
          <NuxtLink to="/articles/chinese-hotpot">Chinese hotpot</NuxtLink>
