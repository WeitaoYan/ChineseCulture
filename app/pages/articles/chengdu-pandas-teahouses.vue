        <h2 class="section-title">Three Day Trips from Chengdu</h2>
        <p class="section-text">
          Chengdu is one of China's best bases for day trips. Three UNESCO
          World Heritage sites lie within a few hours of the city, each from
          a completely different era:
        </p>
        <FeatureGrid>
          <FeatureItem title="🗿 Leshan Giant Buddha" theme="gold">
            <p>
              About two hours south of Chengdu stands the Leshan Giant Buddha,
              a 71-metre statue carved into a riverside cliff in the Tang
              dynasty, over the course of roughly 90 years from circa 713.
              Take the river boat for the full view, then climb the cliffside
              stairway to look the Buddha in the eye. Combine it with a
              morning at the Panda Base only if you start very early — most
              travellers give Leshan a full day.
            </p>
          </FeatureItem>
          <FeatureItem title="💧 Dujiangyan Irrigation System" theme="blue">
            <p>
              Around an hour northwest of the city, Dujiangyan is a 2,000-
              year-old irrigation system built in circa 256 BC under the Qin
              official Li Bing. With no dam at all, it still divides the Min
              River and waters the Chengdu Plain — the fertile "Land of
              Abundance" (天府之国) that made the city possible. Walk the
              Anlan Suspension Bridge and the riverside parks, then continue
              up to Mount Qingcheng, a sacred Daoist mountain, if time
              allows.
            </p>
          </FeatureItem>
          <FeatureItem title="🎭 Sanxingdui Museum" theme="red">
            <p>
              About 40 km north of Chengdu, in Guanghan, the Sanxingdui site
              rewrote the history of Chinese civilisation. Excavated from the
              1980s onwards, it revealed a Bronze Age kingdom of the ancient
              Shu people, circa 12th–11th century BC, whose giant bronze
              masks with bulging eyes and towering sacred trees look like
              nothing else in ancient China. The museum is the single most
              surprising stop on any Chengdu trip — book tickets in advance,
              as it sells out regularly.
            </p>
          </FeatureItem>
        </FeatureGrid>
        <p class="section-text">
          All three are reachable by high-speed train or bus from Chengdu's
          stations, and organised day tours run to each of them. If you only
          have time for one, choose by mood: Leshan for scale, Dujiangyan for
          engineering and scenery, Sanxingdui for sheer mystery.
        </p>
      </section>

