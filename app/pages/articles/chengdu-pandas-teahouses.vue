        <h2 class="section-title">Old Chengdu: Alleys, Shrines and Poets</h2>
        <p class="section-text">
          Chengdu's history stretches back more than 2,000 years, and the old
          city still rewards a slow wander. Start at the
          <strong>Wide and Narrow Alleys</strong> (宽窄巷子, Kuanzhai Xiangzi),
          a restored Qing-dynasty neighbourhood of grey-brick lanes, courtyard
          houses, teahouses and craft shops — the most walkable piece of old
          Chengdu. A short walk away, <strong>Jinli Ancient Street</strong>
          (锦里) recreates the atmosphere of a Shu Kingdom market street,
          busy with snack stalls, lanterns and souvenir shops, especially
          after dark.
        </p>
        <p class="section-text">
          For history, the <strong>Wuhou Shrine</strong> (武侯祠) honours
          Zhuge Liang, the legendary strategist of the Three Kingdoms period
          (circa 3rd century), and his lord Liu Bei — the heroes of the
          classic novel <em>Romance of the Three Kingdoms</em>. Nearby,
          <strong>Du Fu Cottage</strong> (杜甫草堂) preserves the thatched
          home where the great Tang-dynasty poet Du Fu lived in the 750s and
          wrote some of his most famous verse. Together the two sites anchor
          Chengdu's claim to be one of China's great literary cities, and both
          are best visited in the quiet of a weekday morning.
        </p>
        <p class="section-text">
          In the evening, head to <strong>Tianfu Square</strong> and the
          shopping streets around Chunxi Road, or take a walk along the
          Jinjiang River, where the city's modern skyline reflects in the
          water. Chengdu's two faces — the teahouse and the tower block — sit
          closer together here than in almost any other Chinese city.
        </p>
      </section>

