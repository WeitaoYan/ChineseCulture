        <h2 class="section-title">
          The Giant Panda Breeding Research Base
        </h2>
        <p class="section-text">
          The <strong>Chengdu Research Base of Giant Panda Breeding</strong>
          (成都大熊猫繁育研究基地) is not a zoo in the usual sense. Founded in
          1987 on the site of a former bamboo nursery, it is a research and
          breeding centre set in bamboo forest and gardens, where more than a
          hundred giant pandas live in large open-air enclosures. The base
          played a central role in bringing the species back from the brink:
          the giant panda was moved from "endangered" to "vulnerable" on the
          IUCN Red List in 2016, and the Chengdu base's breeding programme is
          a large part of that story.
        </p>
        <p class="section-text">
          Pandas spend most of their waking hours eating bamboo — up to
          three-quarters of the day — and they do almost all of it in the
          morning. By midday, most of them are asleep in the trees or sprawled
          on the grass, and they will not wake up for anyone. The single most
          important piece of advice for the Panda Base is therefore simple:
          <strong>go early</strong>. Arrive at opening time and head straight
          for the Sunlight Nursery and the Moonlight Nursery, where the cubs
          and young pandas are at their liveliest, then work your way around
          the adult enclosures before the crowds — and the pandas — settle
          down for their afternoon nap.
        </p>
        <FeatureGrid>
          <FeatureItem title="🕖 Go Early" theme="gold">
            <p>
              Pandas are most active in the morning, especially around feeding
              time. Arrive at opening and visit the cub nurseries first; by
              early afternoon most pandas are asleep. Weekdays are noticeably
              quieter than weekends and public holidays.
            </p>
          </FeatureItem>
          <FeatureItem title="🚇 Getting There" theme="red">
            <p>
              Take Metro Line 3 to Panda Avenue station, then a short shuttle
              bus or taxi to the entrance. The base is about 10 km northeast of
              the city centre, roughly 30–40 minutes by metro and bus. Ride-
              hailing apps also work well for the return trip.
            </p>
          </FeatureItem>
          <FeatureItem title="🐼 What to See" theme="blue">
            <p>
              The Sunlight and Moonlight Nurseries for cubs, the adult
              enclosures, the red panda area, and the Giant Panda Museum, which
              tells the story of the breeding programme. Allow at least half a
              day — the park is large and mostly outdoors.
            </p>
