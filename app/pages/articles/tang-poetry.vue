      <section class="section">
        <h2 class="section-title">The Legacy of Tang Poetry</h2>
        <p class="section-text">
          Tang poetry did not end with the Tang. Song dynasty poets wrote
          in its shadow and argued with it; later dynasties collected it,
          commented on it, and taught it. In the Qing dynasty, the scholar
          Sun Zhu compiled <em>Three Hundred Tang Poems</em> (唐诗三百首,
          Tángshī Sānbǎi Shǒu) in the 1760s, choosing about three hundred
          poems as an introduction for beginners. The little anthology
          became one of the most widely read books in Chinese history — the
          book through which generations of children first met Li Bai and
          Du Fu — and it is still in print and still memorized today.
        </p>
        <p class="section-text">
          The influence travelled beyond China as well. Tang poetry shaped
          the poetry of Japan and Korea, where Chinese verse was studied
          and imitated for centuries, and in the modern age it has been
          translated into dozens of languages. The images it made famous —
          the bright moon, the lonely traveller, the friend at the gate —
          have become part of the world's shared imagination of China.
        </p>
        <p class="section-text">
          Perhaps the truest measure of Tang poetry is how alive it remains.
          On Mid-Autumn Festival, families still quote Li Bai under the
          full moon. At graduations and farewells, people still reach for
          Wang Wei and Bai Juyi. A poem written twelve centuries ago, in
          twenty or forty characters, can still say exactly what a person
          feels today. That is why the Tang is called the golden age — not
          because it produced the most poetry, but because its poetry has
          never stopped being read.
        </p>
      </section>

