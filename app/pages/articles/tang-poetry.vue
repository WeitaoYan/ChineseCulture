      <section class="section">
        <h2 class="section-title">Why the Tang Dynasty?</h2>
        <p class="section-text">
          Poetry had existed in China for centuries before the Tang — the
          <em>Book of Songs</em> (诗经, Shījīng) dates back more than a
          thousand years earlier — but several things came together in the
          Tang to make poetry flourish as never before. The first was the
          civil service examination system. Under the Tang, the imperial
          examinations became the main road to office, and composing poetry —
          above all, regulated verse — became part of the
          <em>jinshi</em> (进士) examination. A young man hoping for a
          government career had to learn to write a fine poem on a set topic,
          within strict rules of form and rhyme, and under pressure of time.
          Poetry was therefore taught, practiced, and judged everywhere.
        </p>
        <p class="section-text">
          The second was the court itself. Tang emperors and princes were
          patrons of literature, and a good poem could win a poet a post, a
          pension, or a place at court. The emperor Xuanzong (reigned 712–756),
          whose long reign marked the height of Tang culture, gathered poets,
          painters, and musicians around him. Poets wrote for each other as
          well as for the court: friends exchanged poems the way people today
          exchange letters and messages, and a farewell poem at a city gate
          was the normal way to say goodbye.
        </p>
        <p class="section-text">
          The third was the age itself. The Tang was a time of travel and
          movement — officials posted far from home, soldiers on the frontier,
          merchants on the road, monks on pilgrimage. Distance made people
          write: to remember home, to keep a friendship alive, to record a
          landscape they might never see again. The An Lushan Rebellion
          (755–763), which shattered the dynasty's peace and devastated
          Chang'an and Luoyang, also gave poetry its deepest notes of grief
          and witness — most famously in the poems Du Fu wrote as a refugee
          in a ruined capital.
        </p>
      </section>

