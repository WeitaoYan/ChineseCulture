      <section class="section">
        <h2 class="section-title">Overview</h2>
        <p class="section-text">
          <strong>Tang poetry</strong> (唐诗, Tángshī) is the poetry written
          during the Tang dynasty (618–907), and it is widely regarded as the
          golden age of Chinese verse. In three centuries, Chinese poets
          produced a body of work so rich in beauty, feeling, and craft that
          later ages never surpassed it — and that Chinese schoolchildren still
          memorize today, more than a thousand years later.
        </p>
        <p class="section-text">
          The Tang dynasty was a time of unusual openness and confidence.
          Chang'an, the capital, was one of the largest and most cosmopolitan
          cities in the world, home to merchants, monks, musicians, and
          envoys from Central Asia, Persia, India, and beyond. Trade along the
          Silk Road brought wealth, and a strong, stable state brought
          leisure. In such a world, poetry was not a private hobby for a few
          specialists. It was a shared language — the way educated people
          greeted friends, said goodbye, remembered home, and made sense of
          the world.
        </p>
        <p class="section-text">
          What survives is astonishing in scale. The great Qing-dynasty
          collection <em>Complete Tang Poems</em> (全唐诗, Quán Tángshī),
          compiled in the early 1700s, preserves nearly 49,000 poems by more
          than 2,200 poets. And those are only the poems that survived. Tang
          poetry covers almost every human experience: the moon over a quiet
          river, a friend leaving at dawn, a soldier's letter from the
          frontier, the grief of a ruined capital, the joy of a spring walk.
          Its language is plain enough for a child to learn, yet deep enough
          for scholars to study for a lifetime.
        </p>
      </section>

