      <section class="section">
        <h2 class="section-title">The Themes of Tang Poetry</h2>
        <p class="section-text">
          Tang poems return again and again to a handful of great themes.
          They are simple on the surface — the moon, a road, a cup of wine —
          but they carry the deepest feelings of the age:
        </p>
        <FeatureGrid>
          <FeatureItem title="🌙 The Moon &amp; Home" theme="gold">
            <p>
              The moon is the great symbol of Tang poetry: it shines on
              everyone, everywhere, and so it connects the traveller with
              the home he has left behind. To look at the moon was to
              share one sky with absent family and friends. Li Bai's
              moonlit homesickness is only the most famous example.
            </p>
          </FeatureItem>
          <FeatureItem title="👋 Friendship &amp; Farewell" theme="red">
            <p>
              In a world where a posting or an exile could separate friends
              for years — sometimes forever — parting was a constant theme.
              Farewell poems were written at city gates, riverbanks, and
              mountain passes, often with wine, and often with the promise
              that friendship would survive the distance.
            </p>
          </FeatureItem>
          <FeatureItem title="🏔️ Nature &amp; Reclusion" theme="blue">
            <p>
              Mountains, rivers, forests, and snow gave Tang poets a
              language for freedom and for withdrawal from official life.
              Wang Wei's empty mountains and the hermit-poets of the age
              made nature a refuge — and a mirror in which the mind could
              see itself clearly.
            </p>
          </FeatureItem>
          <FeatureItem title="⚔️ War &amp; the Frontier" theme="gray">
            <p>
              The Tang frontier ran far to the west and north, and many
              poems speak of soldiers, cold passes, and the cost of
              empire. Frontier poems (边塞诗) mix pride and pity: the
              glory of guarding the borders, and the grief of those who
              never came home.
            </p>
          </FeatureItem>
        </FeatureGrid>
