      <section class="section">
        <h2 class="section-title">Four Great Poets</h2>
        <p class="section-text">
          Thousands of Tang poets survive in the record, but four names stand
          above all others. Together they show the range of Tang poetry —
          from moonlit freedom to the grief of war:
        </p>
        <FeatureGrid>
          <FeatureItem title="Li Bai (李白, c. 701–762)" theme="gold">
            <p>
              The "Poet Immortal" (诗仙), famous for his imagination,
              spontaneity, and love of wine, the moon, and wandering. Li Bai
              wrote as if poetry came to him in a single breath, and his
              images are among the most quoted in the Chinese language. His
              best-known poem is <em>Quiet Night Thought</em> (静夜思):
            </p>
            <p>
              床前明月光，疑是地上霜。<br />
              举头望明月，低头思故乡。
            </p>
            <p>
              "Before my bed, the moonlight glows — could it be frost upon
              the ground? I lift my head to gaze at the bright moon, and
              lower it, thinking of home." Almost every Chinese child learns
              these twenty characters by heart.
            </p>
          </FeatureItem>
          <FeatureItem title="Du Fu (杜甫, 712–770)" theme="red">
            <p>
              The "Poet Sage" (诗圣), the conscience of the age. Where Li
              Bai soars, Du Fu stays on the ground — writing of war, hunger,
              ruined cities, and ordinary people with a moral seriousness
              no other Chinese poet has matched. During the An Lushan
              Rebellion he wrote <em>Spring View</em> (春望, Chūn Wàng)
              in the ruined capital Chang'an, circa 757:
            </p>
            <p>国破山河在，城春草木深。</p>
            <p>
              "The country is broken, yet mountains and rivers remain; in
              the spring city, grass and trees grow deep." The poem goes on
              to mourn a family scattered by war — and it has been read as
              the voice of China itself in times of disaster ever since.
            </p>
          </FeatureItem>
          <FeatureItem title="Wang Wei (王维, c. 699–761)" theme="blue">
            <p>
              Poet, painter, and musician, the great master of stillness.
              Wang Wei's poems are like ink paintings: empty mountains, a
              deep forest, light falling on moss. His
              <em>Deer Enclosure</em> (鹿柴, Lù Zhài) is a five-character
              quatrain of pure quiet:
            </p>
            <p>
              空山不见人，但闻人语响。<br />
              返景入深林，复照青苔上。
            </p>
            <p>
              "In the empty mountains, no one is seen, yet human voices are
              heard. Evening light slips into the deep forest and shines
              again upon the green moss." The poem says almost nothing — and
              contains a whole world.
            </p>
          </FeatureItem>
          <FeatureItem title="Bai Juyi (白居易, 772–846)" theme="green">
            <p>
              The people's poet, famous for writing in language so plain
              that, by tradition, he would read each new poem to an old
              woman in his household and rewrite any line she could not
              understand. His long narrative <em>Song of Everlasting
              Regret</em> (长恨歌) retells the tragic love of Emperor
              Xuanzong and his consort Yang Guifei, and his
              <em>Farewell to the Grass</em> (赋得古原草送别), written
              when he was young, ends with lines every Chinese reader
              knows:
            </p>
            <p>
              野火烧不尽，春风吹又生。
            </p>
            <p>
              "Wild fire cannot burn it all away; with the spring wind it
              grows again." The grass is a farewell gift to a departing
              friend — and a quiet emblem of endurance.
            </p>
          </FeatureItem>
        </FeatureGrid>
      </section>

