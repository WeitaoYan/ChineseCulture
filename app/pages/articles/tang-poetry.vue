      <section class="section">
        <h2 class="section-title">The Forms of Tang Poetry</h2>
        <p class="section-text">
          Tang poets worked in several forms, and part of their art lay in
          choosing the right form for the right feeling. Two forms dominate
          the age, and both are defined by strict rules that Tang poets
          turned into music:
        </p>
        <FeatureGrid>
          <FeatureItem title="Jueju — The Quatrain (绝句)" theme="gold">
            <p>
              A poem of just four lines, usually of five or seven characters
              each. The quatrain is a miniature: a single scene, a single
              emotion, complete in a breath. Because it is so short, every
              word must earn its place. Li Bai's
              <em>Quiet Night Thought</em> (静夜思) is a five-character
              quatrain, and it is perhaps the most famous poem in China.
            </p>
          </FeatureItem>
          <FeatureItem title="Lüshi — Regulated Verse (律诗)" theme="red">
            <p>
              A poem of eight lines, usually of five or seven characters each,
              governed by strict rules of tonal pattern, rhyme, and
              parallelism: the middle two pairs of lines must match each
              other, line for line, in structure and meaning. Regulated verse
              was the form tested in the civil service examinations, and
              mastering it was a mark of a serious poet. Du Fu is generally
              considered its greatest master.
            </p>
          </FeatureItem>
          <FeatureItem title="Gushi — Old-Style Verse (古诗)" theme="blue">
            <p>
              Poems written in the freer, older style, without the strict
              tonal rules of regulated verse. Old-style verse could run long
              and follow the poet's thought wherever it led, which made it
              the natural form for narratives, laments, and long meditations.
              Many of the Tang's most personal and sweeping poems are in
              this freer form.
            </p>
          </FeatureItem>
          <FeatureItem title="Yuefu — Music Bureau Poems (乐府)" theme="green">
            <p>
              Poems written to old song titles and folk themes, in the
              tradition of the Han dynasty Music Bureau. Yuefu poems often
              speak in the voice of ordinary people — a soldier's wife, a
              frontier guard, a traveller — and they let Tang poets write
              about war, hardship, and daily life in a direct, plain voice.
              Bai Juyi's narrative poems belong to this tradition.
            </p>
          </FeatureItem>
        </FeatureGrid>
        <p class="section-text">
          Underlying these forms is the music of the Chinese language itself.
          Tang regulated verse is built on the pattern of level and oblique
          tones, and on rhymes that fall at the end of even-numbered lines.
          A Tang poem was meant to be read aloud — and often sung. That is
          one reason Tang poems are so memorable: their sound is part of
          their meaning, and a child who learns one by ear can carry it for
          life.
        </p>
      </section>

