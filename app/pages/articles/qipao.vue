          women began to remake it. The robe was shortened, the waist was
          taken in, the sleeves grew short or vanished, and the side slits
          rose. By the 1930s the transformation was complete: the qipao
          had become a fitted, elegant, unmistakably modern dress, and
          Shanghai had become its capital.
        </p>
        <p class="section-text">
          The writer Eileen Chang (Zhang Ailing), who chronicled Shanghai
          life in the 1940s, wrote about the qipao's evolution in her 1943
          essay "A Chronicle of Changing Clothes" (更衣记), tracing how
          Chinese dress had changed year by year. Her essay remains one of
          the best accounts of how the qipao — and Chinese fashion itself
          — became modern.
