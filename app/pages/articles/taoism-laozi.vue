        <h2 class="section-title">The Dao and Wu Wei</h2>
        <p class="section-text">
          Three ideas run through the whole of Taoist thought. Together, they
          form a practical guide to living — not a set of commandments, but a
          way of seeing:
        </p>
        <FeatureGrid>
          <FeatureItem title="🌀 The Dao (道)" theme="gold">
            <p>
              The Dao is the source from which all things arise and the pattern
              they follow. It is not a god and not a lawgiver; it is more like
              the course of a river — invisible itself, but visible in
              everything it carries. The Tao Te Ching calls it the mother of
              all things, empty yet inexhaustible, and says that it nourishes
              everything without possessing anything.
            </p>
          </FeatureItem>
          <FeatureItem title="🌊 Wu Wei (无为)" theme="blue">
            <p>
              <em>Wu wei</em> is usually translated as "non-action" or
              "effortless action." It does not mean doing nothing — it means
              acting without forcing, struggling, or straining against the
              nature of things. Water is the book's favourite image: water never
              argues with a rock, yet over time it wears the rock away. The
              softest thing in the world, Laozi says, overcomes the hardest.
            </p>
          </FeatureItem>
          <FeatureItem title="🌿 Ziran (自然)" theme="green">
            <p>
              <em>Ziran</em> means "self-so" — the way a thing is when left to
              its own nature. A tree does not try to be a tree; it simply
              grows. Taoism asks people to recover that same spontaneity:
              to stop performing, competing, and accumulating, and to trust the
              natural unfolding of life. Simplicity, the book insists, is not
              poverty but freedom.
            </p>
          </FeatureItem>
          <FeatureItem title="☯️ Yin and Yang (阴阳)" theme="gray">
            <p>
              Yin and yang — dark and light, stillness and movement, softness
              and strength — are not enemies but partners, each containing a
              seed of the other. Health, good government, and a good life all
              depend on keeping them in balance rather than letting one side
              dominate. This idea, developed further in the
              <em>I Ching</em> (Book of Changes), became one of the foundations
              of Chinese medicine, cosmology, and art.
            </p>
          </FeatureItem>
          <FeatureItem title="✨ De (德)" theme="yellow">
            <p>
              <em>De</em> — the second word of the book's title — is often
              translated as "virtue" or "power." It is the natural power a
              person or thing has when it follows the Dao: the quiet strength
              of a person who does not need to show off, and the effectiveness
              of a ruler who governs so lightly that the people believe they
              did it themselves.
            </p>
          </FeatureItem>
          <FeatureItem title="🏺 Pu (朴)" theme="red">
            <p>
              <em>Pu</em>, the "uncarved block," is Laozi's image of the
              unspoiled human being — plain wood before it is cut into tools,
              a mind before it is carved up by ambition and desire. The sage,
              the book says, holds to the uncarved block: simple, honest, and
              whole, like a child who has not yet learned to pretend.
            </p>
          </FeatureItem>
