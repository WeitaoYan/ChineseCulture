      <section class="section">
        <h2 class="section-title">Laozi and the Tao Te Ching</h2>
        <p class="section-text">
          Laozi — the name means "Old Master" — is traditionally dated to the
          6th century BCE, which would make him a senior contemporary of
          Confucius. The historian Sima Qian, writing in the 1st century BCE,
          tells the famous story: Laozi, a court archivist weary of the
          decline of the Zhou dynasty, was riding west out of China on a water
          buffalo when a gatekeeper stopped him and asked him to write down his
          wisdom before he disappeared. The result, tradition says, was the
          <em>Tao Te Ching</em> — the <em>Classic of the Way and Virtue</em>.
        </p>
        <p class="section-text">
          Modern scholars debate how much of this story is history and how much
          is legend. The book itself was probably compiled over time, reaching
          its present form around the 4th or 3rd century BCE, and Laozi may be
          a composite figure rather than a single author. What is not in doubt
          is the book's influence. In only 81 short chapters and roughly five
          thousand Chinese characters, it lays out a complete vision of the
          world — and it has become one of the most translated books in
          history, with English versions by scholars, poets, and philosophers
          of every generation.
        </p>
        <p class="section-text">
          The book opens with a paradox that sets the tone for everything that
          follows: the Dao that can be spoken of is not the eternal Dao. The
          deepest truth, it suggests, cannot be captured in words or rules. It
          can only be lived — by observing nature, letting go of striving, and
          aligning oneself with the way things already are.
        </p>
      </section>

