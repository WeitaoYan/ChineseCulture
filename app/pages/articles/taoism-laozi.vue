      <section class="section">
        <h2 class="section-title">Taoism and Confucianism: Two Ways</h2>
        <p class="section-text">
          Confucianism and Taoism are often described as the two poles of the
          Chinese mind, and the contrast is real — but it is a complement, not
          a war. Confucius looked outward: to ritual, duty, family, and good
          government. Laozi looked inward and outward to nature: to
          spontaneity, simplicity, and the wisdom of letting things be.
        </p>
        <p class="section-text">
          A well-known saying captures how the two have coexisted for
          centuries: a scholar might be Confucian in office and Taoist in
          retreat — serving society by day, and finding peace in mountains,
          poetry, and wine when office ended. Chinese culture did not ask people
          to choose one or the other. It offered both, for different moments of
          a life, and trusted each person to find the balance.
        </p>
        <p class="section-text">
          That balance is perhaps Taoism's greatest gift to Chinese civilisation:
          the reminder that order is not the only virtue, that stillness can be
          a form of strength, and that the best action is sometimes the one you
          do not force.
        </p>
