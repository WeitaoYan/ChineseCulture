      <section class="section">
        <h2 class="section-title">
          Philosophical Taoism and Religious Taoism
        </h2>
        <p class="section-text">
          Scholars often distinguish two sides of Taoism that grew from the
          same root. <strong>Philosophical Taoism</strong> (<em>daojia</em>) is
          the tradition of Laozi and Zhuangzi — a way of thinking about nature,
          government, and the good life. <strong>Religious Taoism</strong>
          (<em>daojiao</em>) is the organised faith that took shape from the
          2nd century CE onwards, with temples, clergy, scriptures, and
          rituals. The two have always overlapped, and ordinary Chinese life
          has rarely bothered to separate them.
        </p>
        <FeatureGrid>
          <FeatureItem title="⛰️ The Way of the Heavenly Masters" theme="red">
            <p>
              The earliest organised Taoist movement, founded in the 2nd
              century CE by Zhang Daoling in Sichuan Province. Its priests,
              called Heavenly Masters, healed the sick with confession and
              blessed water, organised communities, and taught that good deeds
              and moral living were the path to a long life. Its lineage
              continues today as the Zhengyi (Orthodox Unity) school.
            </p>
          </FeatureItem>
          <FeatureItem title="🌌 Shangqing and Lingbao" theme="blue">
            <p>
              In the 4th and 5th centuries CE, the Shangqing (Supreme Clarity)
              and Lingbao (Numinous Treasure) schools added rich scriptures,
              visualisations, and rituals. Practitioners meditated on the gods
              within the body, journeyed in spirit to the stars, and recited
              texts believed to grant protection and longevity.
            </p>
          </FeatureItem>
          <FeatureItem title="🧘 Quanzhen (Complete Perfection)" theme="green">
            <p>
              Founded in the 12th century, Quanzhen emphasised inner alchemy
              (<em>neidan</em>) — refining the body's energies through
              meditation, breathing, and moral discipline, rather than seeking
              an external elixir of immortality. Its monks live in monasteries,
              practise celibacy, and are known for their quiet, disciplined way
              of life. The White Cloud Temple in Beijing remains its centre.
            </p>
          </FeatureItem>
          <FeatureItem title="⚗️ The Search for Immortality" theme="gold">
            <p>
              The quest for long life — and, for some, physical immortality —
              drove much of religious Taoism. Early alchemists experimented with
              minerals and herbs, sometimes with fatal results for the emperors
              who drank their elixirs. Over time the search turned inward:
              true immortality, the later masters taught, was a state of
              perfect harmony with the Dao, cultivated within the body and
              mind.
            </p>
          </FeatureItem>
          <FeatureItem title="🏯 Temples and Festivals" theme="yellow">
            <p>
              Taoist temples, often built on sacred mountains such as Mount
              Wudang in Hubei and Mount Qingcheng in Sichuan, are places of
              worship, pilgrimage, and festivals. Devotees burn incense, make
              offerings, and pray for health, good fortune, and protection —
              and temple fairs remain lively community gatherings across China.
            </p>
          </FeatureItem>
