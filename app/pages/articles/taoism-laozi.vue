        <h2 class="section-title">Taoism in Daily Life and Art</h2>
        <p class="section-text">
          Taoism's deepest influence is often the least visible, because it
          dissolved into the everyday fabric of Chinese life:
        </p>
        <p class="section-text">
          In <strong>medicine</strong>, the balance of yin and yang and the
          flow of qi (vital energy) — ideas rooted in Taoist cosmology — became
          central to Traditional Chinese Medicine, from acupuncture to herbal
          remedies and dietary therapy. In <strong>martial arts</strong>,
          tai chi and qigong train the body to move with softness and
          efficiency rather than brute force, turning wu wei into a physical
          discipline practised in parks across China every morning.
        </p>
        <p class="section-text">
          In <strong>art</strong>, Taoism shaped the Chinese landscape
          painting tradition: misty mountains with tiny human figures, vast
          empty space, and the sense that nature, not humanity, is the main
          subject. It shaped <strong>garden design</strong> as well — winding
          paths, irregular rocks, and ponds that imitate wild nature rather
          than imposing geometry on it — and the aesthetics of
          <strong>feng shui</strong>, the art of arranging spaces in harmony
          with their surroundings. In <strong>poetry</strong>, the Tang-dynasty
          poets Li Bai and Wang Wei, steeped in Taoist feeling, wrote of moonlit
          rivers, mountain retreats, and the joy of leaving official life
          behind.
        </p>
        <p class="section-text">
          Even the Eight Immortals — the folk heroes who cross the sea on their
          magic treasures — are Taoist immortals, and their stories show how
          Taoist ideas passed from philosophy into popular legend, opera, and
          New Year prints.
        </p>
      </section>

