        <h2 class="section-title">Overview</h2>
        <p class="section-text">
          <strong>Taoism</strong> (道教, Dàojiào) is one of China's three great
          traditions, alongside Confucianism and Buddhism. At its heart lies a
          single, untranslatable word — the <strong>Dao</strong> (道), usually
          rendered as "the Way." The Dao is the source and the order of all
          things: the path the universe follows, the pattern behind nature, and
          the way of life that brings a person into harmony with it.
        </p>
        <p class="section-text">
          Taoism began as a philosophy, attributed to the sage
          <strong>Laozi</strong> (老子) and his short, profound book, the
          <em>Tao Te Ching</em> (道德经). Over the centuries it grew into an
          organised religion as well, with temples, priests, rituals, and a
          search for immortality — while its philosophical ideas quietly shaped
          Chinese medicine, martial arts, poetry, painting, and garden design.
          Where Confucianism teaches people how to live well together in
          society, Taoism teaches them how to live well with nature and with
          themselves. For more than two thousand years, the two have balanced
          each other in Chinese life.
        </p>
