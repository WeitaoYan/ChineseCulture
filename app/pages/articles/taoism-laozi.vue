      <section class="section">
        <h2 class="section-title">Zhuangzi and the Butterfly Dream</h2>
        <p class="section-text">
          The second great Taoist thinker was <strong>Zhuangzi</strong> (庄子,
          circa 369–286 BCE), author of the book that bears his name. Where the
          <em>Tao Te Ching</em> is terse and oracular, the <em>Zhuangzi</em> is
          playful, witty, and full of stories — a philosopher who argues with
          jokes, paradoxes, and talking trees.
        </p>
        <p class="section-text">
          His most famous passage is the butterfly dream. Zhuangzi once dreamed
          he was a butterfly, fluttering happily, unaware that he was Zhuangzi.
          When he woke, he did not know whether he was Zhuangzi who had dreamed
          he was a butterfly, or a butterfly dreaming he was Zhuangzi. The story
          is not a riddle to be solved but a gentle blow to certainty: if even
          waking and dreaming blur, how firm can our opinions about right and
          wrong, self and other, really be?
        </p>
        <p class="section-text">
          The <em>Zhuangzi</em> delights in characters who flourish by refusing
          to be useful — the gnarled tree too twisted to be cut for timber, and
          so left to live for centuries; the cook whose knife never dulls
          because he cuts along the natural joints of the ox rather than
          hacking through bone. Its lesson is the same as Laozi's, told with a
          smile: skill, freedom, and long life come from following the grain
          of things instead of fighting it.
        </p>
      </section>

