        <h2 class="section-title">Shanghai: China's Front Door</h2>
        <p class="section-text">
          Shanghai is the city most foreign visitors see first — and the
          numbers back that up. It was China's most-visited city by foreign
          travellers in the first half of 2026, welcoming about 5.3 million
          overseas visitors in six months, after roughly 9.4 million inbound
          tourists in 2025. It is also the easiest arrival point: two
          international airports, a metro that reaches almost everywhere, and
          a skyline that makes the scale of modern China visible in a single
          glance.
        </p>
        <p class="section-text">
          Start on <strong>the Bund</strong>, the riverfront promenade where
          colonial-era banks face the towers of Pudong across the Huangpu
          River. Cross over for the view from the Shanghai Tower area, then
          come back down to earth in the <strong>Old City</strong>, where Yu
          Garden — a Ming-dynasty classical garden of rockeries, ponds, and
          zigzag bridges — sits beside streets of snack stalls and tea shops.
          The <strong>French Concession</strong>, with its plane-tree avenues
          and low brick villas, is where Shanghai slows down: cafés, small
          museums, and some of the best people-watching in the country.
        </p>
        <p class="section-text">
          Give Shanghai two to three days. With a spare day, take the
          high-speed train to Suzhou (about 25 minutes) for its classical
          gardens and canals, or to Hangzhou (under an hour) for West Lake —
          both are easy day trips, and both show the gentler, older China that
          lies just beyond the towers.
