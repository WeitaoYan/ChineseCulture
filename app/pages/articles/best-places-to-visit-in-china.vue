          The classic experience is the <strong>Li River cruise</strong> from
          Guilin to Yangshuo, about four hours drifting past fishing villages,
          water buffalo, and cormorant fishermen. Yangshuo itself is the
          relaxed half of the trip: cycle through the countryside to Moon Hill,
          watch the evening light on the Yulong River, and stay a night or two
          instead of rushing back. If you have another day, the
          <strong>Longji rice terraces</strong> — layered fields climbing the
          mountainsides for hundreds of metres — are at their best in late
          spring, when they fill with water, and in autumn, when they turn
          gold.
        </p>
        <p class="section-text">
