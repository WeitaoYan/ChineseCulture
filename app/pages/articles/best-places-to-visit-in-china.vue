          version. <strong>Zhangjiajie National Forest Park</strong> is the
          pillar forest itself — ride the Bailong Elevator, a glass lift
          bolted to a cliff face, up to the viewpoints, then walk the trails
          along the top. <strong>Tianmen Mountain</strong>, a short drive
          away, is the mountain with a natural arch worn through its peak,
          reached by one of the world's longest cable cars and a staircase of
          999 steps. <strong>Zhangjiajie Grand Canyon</strong> holds the
          glass-bottomed bridge suspended some 300 metres above the valley
          floor — thrilling, but only for those comfortable with heights.
        </p>
        <p class="section-text">
          Plan two full days, stay in the town of Wulingyuan rather than the
          city of Zhangjiajie itself, and go in spring or autumn: summer
          brings crowds and haze, winter brings empty trails and sharp, clear
          air. Morning mist is the point — the pillars look their best when
          half-hidden in cloud.
