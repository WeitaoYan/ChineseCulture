          <strong>Liziba</strong>, a metro train passes straight through a
          residential building — through the sixth to eighth floors, to be
          precise. The <strong>Yangtze River cable car</strong> crosses the
          river in the air, and the old streets of Ciqikou offer a quieter,
          older Chongqing of tea houses and small temples.
        </p>
        <p class="section-text">
          Come hungry: Chongqing is the home of the fiercest hotpot in China,
          and the city's night views from the river are among the best in the
          country. Two days is enough to see the highlights; three lets you
          add a Yangtze River cruise downstream through the Three Gorges.
