        <h2 class="section-title">The Tang Golden Age</h2>
        <p class="section-text">
          Buddhism reached its height under the Tang dynasty (618–907), when
          Chang'an was the largest and most cosmopolitan city in the world.
          Tang emperors and empresses patronised monasteries, funded cave
          temples, and welcomed foreign monks; the court of Empress Wu Zetian
          (reigned 690–705) gave Buddhism a prominence it had never enjoyed,
          promoting it as a source of legitimacy and commissioning great
          works of art and translation.
        </p>
        <p class="section-text">
          The Tang was also the age of the great pilgrims and the great
          debates. Monasteries became centres of learning, art, and charity —
          running schools, hostels for travellers, and mills and oil presses
          that funded their work. Buddhist ideas flowed into poetry: the
          Tang poets Wang Wei and Bai Juyi were deeply influenced by Buddhist
          thought, writing of mountain temples, impermanence, and quiet
          contemplation. But the golden age did not last. In 845 CE, Emperor
          Wuzong launched a persecution that closed thousands of monasteries
          and confiscated their wealth, dealing a blow from which institutional
          Buddhism never fully recovered — even as its ideas and practices had
          already become part of Chinese life.
        </p>
      </section>

