              of Buddha images carved into cliffs — from colossal seated Buddhas
              more than fifteen metres tall to niches small enough to hold in
              your hand. Their style shows Buddhism's journey: the earliest
              Buddhas look Central Asian, the later ones unmistakably Chinese.
            </p>
