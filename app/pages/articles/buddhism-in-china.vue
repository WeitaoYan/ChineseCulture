        <h2 class="section-title">Arrival on the Silk Road</h2>
        <p class="section-text">
          Buddhism entered China during the Han dynasty, in the 1st century CE,
          carried by merchants and missionaries along the overland Silk Road
          through Central Asia and by sea to the southern ports. According to a
          famous legend, Emperor Ming of Han (reigned 58–75 CE) dreamed of a
          golden figure floating in his hall; his advisers told him it was the
          Buddha, a sage of the West. He sent envoys to seek the teaching, and
          they returned with two Indian monks and Buddhist scriptures carried
          on a white horse.
        </p>
        <p class="section-text">
          Whether or not the legend is literally true, the <strong>White Horse
          Temple</strong> (白马寺) in Luoyang — traditionally dated to 67 CE and
          regarded as the first Buddhist temple in China — still stands today
          as a monument to that first encounter. In the early centuries,
          Buddhism spread slowly, carried by foreign monks and welcomed mainly
          in cosmopolitan trading cities. Chinese readers first met it through
          translations, and the translators faced a formidable problem: how do
          you render Indian ideas like emptiness, karma, and nirvana in a
          language that has no words for them?
        </p>
        <p class="section-text">
          The solution was to borrow the vocabulary of Taoism. Translators
          rendered Buddhist terms with Taoist ones — <em>wu wei</em> for
          nirvana, <em>Dao</em> for the path to awakening — and early Chinese
          readers understood Buddhism as a kind of foreign Taoism. The
          misunderstanding was productive: it gave Buddhism a Chinese voice,
          and it began the long conversation between the two traditions that
          would reshape both.
        </p>
