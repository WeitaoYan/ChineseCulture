            <p>
              The pagoda — adapted from the Indian stupa — became one of China's
              most recognisable buildings. Originally built to house relics of
              the Buddha, pagodas of wood, brick, and stone rose over temples
              and cities, from the Giant Wild Goose Pagoda in Xi'an, built to
              hold Xuanzang's sutras, to the slender towers that still mark old
              towns across the south.
            </p>
