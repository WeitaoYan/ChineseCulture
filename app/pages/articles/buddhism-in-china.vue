        <h2 class="section-title">Buddhism in Daily Life</h2>
        <p class="section-text">
          For most Chinese people, Buddhism is met not in philosophy books but
          in everyday moments. The bodhisattva <strong>Guanyin</strong>
          (观音) — originally the Indian Avalokitesvara, transformed in China
          into a compassionate goddess — is perhaps the most widely worshipped
          figure in Chinese folk religion, prayed to for children, health, and
          rescue from danger. Her birthday, on the 19th day of the second lunar
          month, draws crowds to temples across the country.
        </p>
        <p class="section-text">
          The Buddha's Birthday, on the eighth day of the fourth lunar month,
          is celebrated with the ritual bathing of a statue of the infant
          Buddha. Vegetarianism, promoted by Buddhist monasteries, shaped
          Chinese temple cuisine — and through it, a whole tradition of
          vegetarian cooking that imitates meat dishes with tofu, gluten, and
          mushrooms. Temple fairs, incense offerings, the chanting of sutras
          for the dead, and the release of captive animals as an act of merit
          are all part of the fabric of Chinese life, practised by people who
          may never call themselves Buddhists at all.
        </p>
        <p class="section-text">
          Buddhism in China today remains a living tradition: temples are
          active places of worship and pilgrimage, monks and nuns continue to
          teach and practise, and its ideas — impermanence, compassion, and
          the interconnection of all things — continue to speak to new
          generations, in China and far beyond.
        </p>
