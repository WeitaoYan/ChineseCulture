        <h2 class="section-title">The Three Teachings</h2>
        <p class="section-text">
          Buddhism did not replace Confucianism or Taoism; it joined them.
          Over the centuries, the three traditions came to be known as the
          <strong>Three Teachings</strong> (三教, <em>San Jiao</em>), and
          Chinese thinkers increasingly treated them as complementary rather
          than competing. A popular saying held that the three teachings were
          one family: Confucianism for ordering society, Taoism for nourishing
          the body and following nature, Buddhism for understanding the mind
          and the fate of the soul.
        </p>
        <p class="section-text">
          The blending ran deep. Neo-Confucian thinkers of the Song dynasty
          (960–1279) borrowed Buddhist ideas about the mind and human nature
          even while criticising Buddhism itself. Chan Buddhism absorbed Taoist
          language and spontaneity, so that Zen in later centuries would feel
          as much Taoist as Buddhist. Temples often housed Confucius, Laozi,
          and the Buddha side by side, and ordinary families mixed the three
          traditions without a second thought — burning incense to Guanyin,
          honouring ancestors in the Confucian manner, and consulting the
          <em>I Ching</em> for guidance.
        </p>
      </section>

