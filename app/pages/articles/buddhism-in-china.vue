        <h2 class="section-title">Translation and Transformation</h2>
        <p class="section-text">
          The great age of translation began in the 4th and 5th centuries CE.
          <strong>Kumarajiva</strong> (344–413), a monk from the Central Asian
          kingdom of Kucha, led a state-sponsored translation bureau in the
          northern capital of Chang'an and produced elegant, readable Chinese
          versions of the <em>Lotus Sutra</em> and other key texts — versions
          still chanted today. His translations fixed the Chinese vocabulary
          of Buddhism and made the teaching accessible to a Chinese audience
          for the first time.
        </p>
        <p class="section-text">
          Two centuries later, the monk <strong>Xuanzang</strong> (602–664)
          made the most famous journey in Chinese religious history. Dissatisfied
          with the translations available, he set out alone in 629 CE, crossing
          deserts and mountains to India, where he studied for more than a
          decade and returned with hundreds of sutras. His pilgrimage became
          the stuff of legend — and centuries later, the inspiration for
          <em>Journey to the West</em> (西游记), one of the Four Great Classical
          Novels, in which Xuanzang travels to India protected by the Monkey
          King.
        </p>
        <p class="section-text">
          Through translation, Buddhism was not simply imported; it was
          remade. Chinese monks asked questions Indian Buddhism had not asked:
          can a single teaching hold all the sutras together? Does the Buddha
          nature live in every person? Can awakening happen suddenly, in a
          single moment? The answers became distinctively Chinese schools of
          Buddhism.
        </p>
      </section>

