        <p class="section-text">
          Of all the schools that grew up in China, two became the most
          enduring — and they could hardly be more different. One seeks
          awakening through meditation and sudden insight; the other, through
          simple faith and the repetition of a single name:
        </p>
        <FeatureGrid>
          <FeatureItem title="🧘 Chan (禅宗)" theme="gold">
            <p>
              Chan — known in the West as Zen, from its Japanese name — teaches
              that awakening comes not from studying scriptures but from direct
              insight into one's own mind. Tradition traces it to Bodhidharma,
              an Indian monk said to have arrived in China in the 5th or 6th
              century and to have meditated facing a wall for nine years. The
              sixth patriarch, Huineng (638–713), taught that enlightenment
              could come suddenly, in an ordinary moment, and that it belonged
              to everyone — not only to scholars and monks. Chan masters taught
              with paradoxes, shouts, and riddles called <em>gong'an</em>
              (koans), designed to break the habit of thinking in words.
            </p>
          </FeatureItem>
          <FeatureItem title="🌸 Pure Land (净土宗)" theme="red">
            <p>
              Pure Land Buddhism offers a simpler path: sincere devotion to
              Amitabha Buddha, the Buddha of Infinite Light, and the repeated
              chanting of his name — <em>Namo Amituofo</em> ("Homage to Amitabha
              Buddha"). The faithful believe that even ordinary people, unable
              to reach awakening by their own effort, can be reborn in
              Amitabha's Western Paradise, a realm where enlightenment is easy.
              It became the most widely practised form of Buddhism in China,
              and its chant is still heard in temples and homes today.
            </p>
          </FeatureItem>
          <FeatureItem title="🏔️ Tiantai (天台宗)" theme="blue">
            <p>
              Founded by the monk Zhiyi (538–597) on Mount Tiantai, this school
              sought to organise all the Buddha's teachings into a single
              system, teaching that all beings possess the Buddha nature and
              that the <em>Lotus Sutra</em> holds the key to reconciling the
              many different sutras. Its method of meditation, "cessation and
              contemplation," became a model for Buddhist practice across East
              Asia.
            </p>
          </FeatureItem>
          <FeatureItem title="🌺 Huayan (华严宗)" theme="green">
            <p>
              Based on the <em>Avatamsaka Sutra</em> (Flower Garland Sutra),
              Huayan teaches the interpenetration of all things — that each
              single thing contains the whole universe, as each jewel in the
              god Indra's net reflects every other jewel. Its vision of a
              world in which everything is connected to everything else
              profoundly influenced Chinese philosophy, art, and poetry.
            </p>
