        <p class="section-text">
          The third attraction is the Zhangjiajie Grand Canyon (张家界大峡谷),
          about an hour's drive from the city in a different direction from
          the forest park. Its claim to fame is the <strong>Glass
          Bridge</strong> (玻璃桥), opened in 2016: a transparent footbridge
          roughly 430 metres long, suspended about 300 metres above the
          canyon floor. At the time it opened it was the longest and highest
          glass bridge in the world, and walking across it — the river a
          long way below your feet — is still the most vertigo-inducing
          minute in Zhangjiajie.
        </p>
        <p class="section-text">
          The canyon itself is worth the trip even without the bridge: a
          deep, green gorge with waterfalls, a lake, and a walkway along the
          cliff, plus a long slide and a zip line for the adventurous. The
          bridge is the headline, but the canyon is the day. Book the bridge
          in advance — daily numbers are capped, and it sells out on
          holidays — and note that the bridge ticket and the canyon ticket
          are sold separately. Prices change with the season; check the
          official channels before you go.
        </p>
      </section>

