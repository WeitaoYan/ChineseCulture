        <h2 class="section-title">Overview</h2>
        <p class="section-text">
          <strong>Zhangjiajie</strong> (张家界, Zhāngjiājiè) is the place
          where the movie <em>Avatar</em>'s floating Hallelujah Mountains
          come down to earth. In the Wulingyuan scenic area, more than 3,000
          quartzite sandstone pillars rise out of the forest like stone
          fingers, some of them hundreds of metres tall, wrapped in mist and
          crowned with pine trees. On a foggy morning, when the cloud sits
          below the peaks and only the tops show, the pillars really do look
          as if they are floating — and you will understand, in about five
          seconds, why this is one of the most photographed landscapes in
          China. It is also the living original of the misty mountain
          scenes in classical
          <NuxtLink to="/articles/chinese-painting">Chinese painting</NuxtLink>.
        </p>
