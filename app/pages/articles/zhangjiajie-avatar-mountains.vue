      <section class="section">
        <h2 class="section-title">Tianmen Mountain: The Stairway to Heaven</h2>
        <p class="section-text">
          Tianmen Mountain (天门山) is a different kind of thrill from the
          forest park, and it sits almost in the city itself — the cable car
          station is a short walk from Zhangjiajie railway station, and the
          ride up is about 30 minutes, one of the longest passenger cable
          cars in the world, climbing over the city and up the forested
          mountainside.
        </p>
        <p class="section-text">
          The landmark is <strong>Tianmen Cave</strong> (天门洞), a natural
          arch about 130 metres high that punches clean through the mountain
          near the summit — the "Gate to Heaven" of the name. Reaching it is
          half the experience: the road up the mountain, the Tongtian Avenue,
          winds through 99 hairpin bends, and the final approach is a flight
          of 999 steps up to the arch itself. The number is deliberate — nine
          is the most auspicious number in Chinese tradition — and by the top
          of the stairs your legs will agree that it is a serious climb.
        </p>
        <p class="section-text">
          The mountain's other famous feature is its cliffside glass
          skywalk, a narrow transparent walkway bolted to the rock face high
          above the valley — not to be confused with the Grand Canyon's glass
          bridge, which is a different attraction in a different place. The
          skywalk is short and optional, and shoe covers are provided. The
          summit itself has temples, a loop trail, and views back over the
          city and the surrounding peaks. Allow half a day at a brisk pace, a
          full day if you walk the summit trails.
        </p>
      </section>

