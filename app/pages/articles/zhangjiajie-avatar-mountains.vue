        <h2 class="section-title">When to Go, and What to Know Before You Go</h2>
        <p class="section-text">
          <strong>Best seasons.</strong> Spring (April–May) and autumn
          (September–October) are the most comfortable, with mild
          temperatures and the best chance of the drifting mist that makes
          the pillars look like they float. Summer is green and lush but hot,
          crowded, and rainy; winter is cold and quiet, and the pillars under
          snow are spectacular — but fog can close the viewpoints, and the
          cable cars sometimes stop in high wind.
        </p>
        <p class="section-text">
          <strong>Crowds.</strong> Zhangjiajie is one of China's most
          popular domestic destinations, and the queues for the Bailong
          Elevator and the Tianmen cable car can stretch to hours on Chinese
          public holidays. Avoid the first week of October (National Day),
          the May Day holiday, and the Spring Festival if you can; on any
          day, start early and visit the famous viewpoints first.
        </p>
        <p class="section-text">
          <strong>Getting there.</strong> Zhangjiajie has its own airport
          (DYG) with flights from major Chinese cities, and a high-speed
          rail station with connections to Changsha (about 3 hours) and
          beyond. The city is small by Chinese standards, and buses and taxis
          connect the station, the city centre, and the three scenic areas —
          but allow real travel time between them, and book tickets for each
          attraction separately, in advance, on the official channels.
        </p>
        <p class="section-text">
          <strong>Fitness.</strong> This is a walking trip: stairs, steep
          trails, and long days on your feet, even with the cable cars and
          elevators doing the heavy lifting. Wear proper walking shoes, carry
          water, and take the shuttle buses inside the forest park instead of
          trying to walk between its areas.
        </p>
