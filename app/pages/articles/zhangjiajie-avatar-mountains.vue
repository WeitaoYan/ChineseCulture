        <p class="section-text">
          This is the single most useful thing to know before you book
          anything. "Zhangjiajie" is the name of the city, and three different
          attractions around it share the name in their marketing. They are
          in different locations, they sell different tickets, and you cannot
          walk from one to the other:
        </p>
        <FeatureGrid>
          <FeatureItem title="1. Wulingyuan — the Pillars" theme="green">
            <p>
              The Zhangjiajie National Forest Park, in the Wulingyuan
              district about 40 minutes by road from the city centre. This is
              where the Avatar pillars are: Yuanjiajie, Tianzi Mountain, and
              the Golden Whip Stream valley. One multi-day ticket, one big
              park, the main event. Budget a full day, ideally two.
            </p>
          </FeatureItem>
          <FeatureItem title="2. Tianmen Mountain — the Hole in the Mountain" theme="blue">
            <p>
              Right next to the city centre, reached by one of the world's
              longest cable cars from the railway station. Its landmark is
              Tianmen Cave (天门洞), a natural arch through the mountain, with
              99 hairpin bends on the road below it and a cliffside glass
              skywalk. Half a day to a full day; a different mountain, a
              different ticket.
            </p>
          </FeatureItem>
          <FeatureItem title="3. Zhangjiajie Grand Canyon — the Glass Bridge" theme="red">
            <p>
              A separate canyon about an hour from the city, home to the
              Zhangjiajie Glass Bridge (张家界大峡谷玻璃桥) — a transparent
              footbridge spanning the gorge, opened in 2016. Half a day. It is
              not inside the forest park, and the forest park ticket does not
              cover it.
            </p>
          </FeatureItem>
        </FeatureGrid>
        <p class="section-text">
          The classic booking mistake is buying a "Zhangjiajie ticket" and
          assuming it covers everything. It never does. Check exactly which
          scenic area each ticket is for before you pay, and allow travel
          time between them — they are spread across the region, not stacked
          on top of each other.
        </p>
      </section>

