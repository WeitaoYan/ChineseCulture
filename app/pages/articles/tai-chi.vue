          China's most recognizable traditions: a slow, flowing sequence of
          movements performed at dawn in parks across the country, by people
          of every age. To a passerby it looks like a graceful dance. In
          truth it is a martial art, a form of moving meditation, and a
          living piece of Chinese philosophy — all at once.
