        <h2 class="section-title">Origins in Chenjiagou</h2>
        <p class="section-text">
          Tai chi was created in the 17th century in Chenjiagou (陈家沟), a
          small village in Wen County, Henan Province. Its founder is
          traditionally identified as Chen Wangting (陈王廷, c. 1580–1660),
          a Ming-dynasty military officer of the Chen family who, after
          retiring from service in the turbulent years of the Ming–Qing
          transition, combined the martial arts he knew with the breathing
          and health practices of traditional Chinese medicine and Daoist
          cultivation. The result was a new art: fighting techniques
          softened and slowed into a continuous, circular flow.
        </p>
        <p class="section-text">
          For some two hundred years, tai chi remained a closely guarded
          family secret of the Chen clan, taught only to family members and
          a handful of trusted disciples in Chenjiagou. That changed in the
          19th century, when Yang Luchan (杨露禅, 1799–1872), an outsider
          from Hebei, managed to learn the art in the village and carried it
          to Beijing. There he taught the imperial family and the capital's
          elite, earning the nickname "Yang the Invincible" (杨无敌) — and
          tai chi began its journey from a village secret to a national
          treasure.
        </p>
        <p class="section-text">
          From Yang's teaching, and from later masters who each reshaped
          what they learned, the great family styles of tai chi emerged.
          Each keeps the same core principles but moves with a different
          character — proof that one root can grow many branches.
        </p>
      </section>

