            </p>
          </FeatureItem>
          <FeatureItem title="Yang Style (杨式)" theme="gold">
            <p>
              Founded by Yang Luchan in the 19th century and later
              standardized by his grandson Yang Chengfu (1883–1936). Large,
              open, graceful frames, even speed, and upright posture make it
              the most widely practiced style in the world — the gentle,
              flowing form most people picture when they think of tai chi.
            </p>
          </FeatureItem>
          <FeatureItem title="Wu Style (吴式)" theme="blue">
            <p>
              Developed by Wu Quanyou (1834–1902), a Manchu bannerman who
              studied under Yang Luchan. Wu style uses smaller, more compact
              movements, a slight forward lean, and a distinctive
              "push-hands" emphasis. It remains especially popular in
              Shanghai and among overseas Chinese communities.
            </p>
          </FeatureItem>
          <FeatureItem title="Wu / Hao Style (武式)" theme="green">
            <p>
              Founded by Wu Yuxiang (1812–1880) of Hebei, a scholar who
              learned from Yang Luchan and Chen Qingping and wrote some of
              the earliest tai chi treatises. Its small, refined frames and
              strong theoretical writings make it the most scholarly of the
              styles — sometimes called Hao style after its later promoter,
              Hao Weizhen.
            </p>
          </FeatureItem>
          <FeatureItem title="Sun Style (孙式)" theme="yellow">
            <p>
              The youngest of the five, created in the early 20th century by
              Sun Lutang (1861–1933), a master of three internal arts.
              Sun style blends tai chi with the agile footwork of bagua and
              xingyi, features lively stepping with the feet following the
              hands, and is often recommended for older practitioners
              because of its upright posture and nimble movement.
            </p>
          </FeatureItem>
