          <FeatureItem title="Chen Style (陈式)" theme="red">
            <p>
              The oldest style, closest to the art's martial roots. Chen
              style alternates slow, soft movements with sudden bursts of
              power (发劲, <em>fajin</em>), low stances, and coiling,
              silk-reeling motions (缠丝劲). It is the most visibly
              athletic of the styles and the one still taught in
