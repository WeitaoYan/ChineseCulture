              (September–October) are ideal: mild, dry, and clear. Winters are
              cold and dry, often below freezing; summers are hot, with July
              and August the wettest months. The Great Wall is at its best in
              autumn colour or spring green — and at its emptiest in winter.
            </p>
          </FeatureItem>
          <FeatureItem title="🌴 South — Shanghai, Guangzhou, Guilin" theme="green">
            <p>
              Warm and humid, with a long summer and a short, damp winter.
              Spring and autumn are the most comfortable; the rainy season
              runs roughly from May to August, and typhoons can brush the
              coast from July to September. Guilin's Li River is beautiful
              year-round, but clearest in autumn.
            </p>
          </FeatureItem>
          <FeatureItem title="🌸 Southwest — Yunnan, Chengdu" theme="gold">
            <p>
              The mildest climate in China. Kunming is called the "Spring
              City" for a reason: daytime temperatures stay comfortable in
              almost every month. Spring (March–May) is the peak season for
              Dali, Lijiang, and Shangri-La; the summer rains (June–August)
              are heavy but usually fall in the afternoon.
            </p>
          </FeatureItem>
          <FeatureItem title="🏜️ West — Tibet, Xinjiang, the Silk Road" theme="blue">
            <p>
