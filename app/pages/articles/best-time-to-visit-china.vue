      <section class="section">
        <h2 class="section-title">The Short Answer: Spring and Autumn Win</h2>
        <p class="section-text">
          If you only remember one thing from this guide, remember this: plan
          for <strong>April–May or September–October</strong>, and avoid the
          three great holiday crushes — <strong>Spring Festival</strong> (late
          January or February), the <strong>May Day holiday</strong> (around 1
          May), and <strong>National Day Golden Week</strong> (1–7 October).
          Here is how the four seasons compare:
        </p>
