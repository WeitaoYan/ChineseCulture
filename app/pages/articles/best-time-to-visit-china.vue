      <section class="section">
        <h2 class="section-title">Month by Month: July to August</h2>
        <p class="section-text">
          <strong>July and August</strong> are the hottest months and the
          peak of the domestic summer holiday. Expect temperatures above 30°C
          (86°F) in most cities, higher in the Yangtze valley, with humidity
          to match — and afternoon thunderstorms in the south. The Forbidden
          City, the Terracotta Army, and the Bund are at their most crowded,
          and hotel prices in family destinations climb.
        </p>
        <p class="section-text">
          Summer is not a bad time to visit China; it is simply a time to
          choose your destinations well. The mountains are the escape:
          Zhangjiajie's peaks are cooler than the lowlands, the Yellow
          Mountains (Huangshan) are wrapped in the sea of clouds that Chinese
          painters made famous, and the high-altitude west — Tibet, Qinghai
          Lake, the Altay grasslands of Xinjiang — is in its best and almost
          only comfortable season. If you travel in summer, start sightseeing
          early, rest in the midday heat, and keep a flexible day in your plan
          for rain.
        </p>
      </section>

