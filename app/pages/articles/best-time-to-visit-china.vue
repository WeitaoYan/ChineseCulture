        <p class="section-text">
          China spans tropical Hainan in the south to sub-Arctic Heilongjiang
          in the north, and from the deserts of Xinjiang in the west to the
          humid coast in the east. The "best time" is really a regional
          question:
        </p>
        <FeatureGrid>
          <FeatureItem title="🏯 North — Beijing, Xi'an" theme="red">
            <p>
