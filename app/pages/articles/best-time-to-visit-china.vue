          <strong>autumn (September–October)</strong>. These are the two windows
          when the weather is mild across most of the country, the skies are at
          their clearest, and the landscapes are at their most photogenic —
          cherry blossom and fresh green in spring, golden leaves and crisp air
          in autumn.
