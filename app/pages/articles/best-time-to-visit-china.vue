        <h2 class="section-title">Month by Month: September to December</h2>
        <p class="section-text">
          <strong>September</strong> is autumn's opening act and one of the
          finest months of the year: the summer heat breaks, the rain eases,
          and the crowds of the school holidays vanish. The Great Wall under
          a blue September sky, the karst peaks of Guilin in clear air, and
          the first red leaves in the mountains all argue for September. It is
          also the month of the
          <NuxtLink to="/articles/mid-autumn-festival">Mid-Autumn Festival</NuxtLink>,
          when families gather under the full moon and mooncakes appear
          everywhere — a lovely time to be in China if you plan around the
          short holiday itself.
        </p>
        <p class="section-text">
          <strong>October</strong> is the month of the great divide. The
          first week — <strong>National Day Golden Week, 1–7 October</strong>
          — is the single busiest travel week in China, when hundreds of
          millions of people are on the move and the famous sights are
          shoulder to shoulder. Avoid it. But from mid-October onward, the
          country is glorious: autumn colour peaks around Beijing and in the
          mountains, the air is crisp and dry in the north, and Zhangjiajie's
          forests turn gold and red. Late October is, for many repeat
          travellers, the best week of the year.
        </p>
        <p class="section-text">
          <strong>November</strong> is the quiet season's sweet spot — and
          the planning season for the spring to come. Search interest in
          Harbin trip planning peaks in November, as travellers book the
          winter festival ahead. The north turns cold and the leaves fall, but
          the south stays mild: Guangzhou, Shenzhen, and Xiamen are
          comfortable, and Yunnan is still pleasant. Prices drop, crowds
          vanish, and the light in the deserts of the northwest is at its
          clearest.
        </p>
        <p class="section-text">
          <strong>December</strong> brings winter proper. The north is cold
          and dry, the south damp and chilly — southern cities are often
          colder indoors than out, since central heating is rare south of the
          traditional Qinling–Huaihe line. But December is also when Harbin's
          Ice and Snow World opens, usually in late December, and when
          Beijing's Forbidden City under snow is at its most beautiful and
          least crowded. Pack warm layers and you will have the great sights
          almost to yourself.
        </p>
      </section>

