      <section class="section">
        <h2 class="section-title">Crowds and Prices: High Season vs Low Season</h2>
        <p class="section-text">
          China's high season runs roughly from April to October, with sharp
          peaks at May Day, the summer school holidays, and Golden Week. The
          low season is November to March, except for Harbin and the ski
          resorts. The difference is real: in the low season, popular hotels
          can cost noticeably less, the great sights are walkable rather than
          packed, and same-day train tickets are far easier to find.
        </p>
        <p class="section-text">
          The trade-off is the weather — and the daylight. A January trip to
          Beijing means short, cold days; a July trip means long, hot ones.
          The shoulder months are where the balance is best: late March and
          November for the south, April–May and September–October for the
          north, and the weeks immediately after each big holiday, when prices
          fall and the crowds have just left.
        </p>
        <p class="section-text">
          One practical tip applies in every season: book the headline
          attractions ahead. The Forbidden City, the Terracotta Army, and the
          Shanghai Tower all cap daily visitors, and tickets can sell out days
          in advance in the high season — and even in the shoulder season on
          weekends. A little planning buys you the trip the calendar promised.
        </p>
      </section>

