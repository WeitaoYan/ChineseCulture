          United States, and "the best time" depends on where you are going.
          Harbin in the far north is a winter destination built around ice and
          snow, while Yunnan in the southwest feels like spring almost all year
          round. The rainy season soaks the south in summer, the deserts of the
          northwest are at their best in autumn, and the great festivals that
          draw visitors also bring the year's biggest crowds. This guide walks
          through the year month by month, region by region, so you can pick
          the season that fits your trip — and dodge the holidays when a
          billion people travel at once.
        </p>
