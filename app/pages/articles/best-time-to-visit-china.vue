          <FeatureItem title="🌸 Spring (March–May)" theme="green">
            <p>
              The classic best season. Temperatures climb into the comfortable
              range across central and northern China, flowers bloom from
              Kunming to Luoyang, and the summer rains have not yet arrived.
              April and May are the sweet spot; March can still be chilly in
              the north. The one exception is the May Day holiday, when
              domestic travel surges for several days around 1 May.
            </p>
          </FeatureItem>
          <FeatureItem title="☀️ Summer (June–August)" theme="yellow">
            <p>
              Hot, humid, and rainy across much of the country, with school
              holidays filling family attractions in July and August. The
              upside: long days, green mountains, and the best season for
              high-altitude places such as Tibet's plateau and the grasslands
              of Inner Mongolia. Carry rain gear and book the big sights early
              in the morning.
            </p>
          </FeatureItem>
          <FeatureItem title="🍁 Autumn (September–November)" theme="red">
            <p>
              The other classic best season — many travellers' favourite.
              September and October bring clear skies, mild temperatures, and
              autumn colour from the Great Wall to Zhangjiajie. The catch is
              Golden Week (1–7 October), the busiest travel week of the year.
              Travel just before it, or in late October and November, and the
              crowds thin out fast.
            </p>
