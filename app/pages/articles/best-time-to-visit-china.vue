              is the whole point. Expect the cheapest hotels and the emptiest
              sights in Beijing, Xi'an, and Shanghai, but also cold, dry days
              in the north and damp chill in the south. Spring Festival falls
              in this window and turns the country into the world's largest
              annual migration.
            </p>
