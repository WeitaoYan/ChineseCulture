      <section class="section">
        <h2 class="section-title">Month by Month: April to June</h2>
        <p class="section-text">
          <strong>April</strong> is, for many travellers, the single best
          month to visit China. Beijing's parks fill with blossom, the Great
          Wall is green again, Xi'an is warm but not hot, and the mountains
          of Zhangjiajie shake off the winter mist. It is also the month of
          <NuxtLink to="/articles/qingming-festival">Qingming Festival</NuxtLink>
          (Tomb-Sweeping Day, early April), a short public holiday that brings
          a brief surge of domestic travel — worth knowing about, but nothing
          like the big holiday crushes.
        </p>
        <p class="section-text">
          <strong>May</strong> is nearly as good, with one warning: the
          <strong>May Day holiday</strong> around 1 May packs trains, hotels,
          and every famous sight for several days. Travel in mid-to-late May
          instead and you get late-spring warmth with the crowds gone. Yunnan
          is at its best in May — mild days in Dali and Lijiang before the
          summer rains — and the
          <NuxtLink to="/articles/dragon-boat-festival">Dragon Boat Festival</NuxtLink>,
          which usually falls in May or June, brings dragon boat races to
          rivers and lakes across the south.
        </p>
        <p class="section-text">
          <strong>June</strong> marks the turn into summer. The south enters
          its rainy season, and the heat builds in the Yangtze valley cities
          such as Shanghai, Chongqing, and Wuhan. But June has its rewards:
          the rice terraces of Longji and Yuanyang are flooded and mirror-like
          in early summer, and the high plateau destinations — Tibet, Qinghai,
          the grasslands — open up for their short, glorious season. If you
          travel in June, plan around afternoon rain in the south and book
          mountain stays early.
        </p>
      </section>

